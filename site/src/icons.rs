#[cfg(test)]
mod tests {
    use super::*;
    use crate::content::{PAGES, Section};

    #[test]
    fn every_page_and_section_has_an_icon() {
        for page in PAGES {
            assert!(
                !svg(page.icon).is_empty(),
                "{}: no icon {}",
                page.slug,
                page.icon
            );
        }
        for section in Section::ALL {
            assert!(!svg(section.icon()).is_empty(), "{section:?}");
        }
        assert_eq!(svg("nope"), "");
    }
}
