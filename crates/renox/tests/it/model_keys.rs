/// A key the app picks: a customer code.
#[derive(Model, serde::Serialize, Default, Debug, Clone, PartialEq)]
#[model(table = "customers")]
struct Customer {
    id: String,
    name: String,
}

#[derive(Model, serde::Serialize, Default, Debug, Clone, PartialEq)]
#[model(table = "invoices", soft_deletes)]
struct Invoice {
    id: Ulid,
    customer_id: Option<String>,
    number: String,
    total: i64,
    created_at: Option<DateTime>,
    updated_at: Option<DateTime>,
    deleted_at: Option<DateTime>,
}

#[derive(Model, serde::Serialize, Default, Debug, Clone)]
#[model(table = "lines")]
struct Line {
    id: i64,
    invoice_id: Ulid,
    amount: i64,
}

#[derive(Model, serde::Serialize, Default, Debug, Clone, PartialEq)]
#[model(table = "tags")]
struct Tag {
    id: i64,
    name: String,
}

#[derive(Model, serde::Serialize, Default, Debug, Clone)]
#[model(table = "notes")]
struct Note {
    id: i64,
    noteable_type: String,
    noteable_id: Ulid,
    body: String,
}

#[derive(FromRow)]
struct Tagging {
    note: String,
}

const INVOICE_TAGS: Pivot<Ulid, i64> = Pivot::new("invoice_tags", "invoice_id", "tag_id");
const NOTEABLE: Morph = Morph::new("noteable_type", "noteable_id");

async fn app() -> TestApp {
    TestApp::new(App::new().migrations(&[SCHEMA])).await
}

async fn invoice(db: &Db, number: &str, total: i64, customer: Option<&str>) -> Invoice {
    Invoice::create(
        db,
        Invoice {
            number: number.into(),
            total,
            customer_id: customer.map(Into::into),
            ..Default::default()
        },
    )
    .await
    .unwrap()
}

#[renox::test]
async fn ulid_keys_are_made_on_insert() {
    let app = app().await;
    let db = app.db();
    let first = invoice(db, "INV-1", 10_000, None).await;
    assert_eq!(first.id.as_str().len(), 26);
    assert!(first.created_at.is_some());

    // `save` on a new model inserts it too, with a later key.
    let mut second = Invoice {
        number: "INV-2".into(),
        total: 5_000,
        ..Default::default()
    };
    second.save(db).await.unwrap();
    assert!(second.id > first.id, "ULIDs sort by creation");

    // Found by key; saving a loaded model updates it.
    let mut found = Invoice::find_or_404(db, first.id.clone()).await.unwrap();
    assert_eq!(found, first);
    found.total = 12_000;
    found.save(db).await.unwrap();
    assert_eq!(
        Invoice::find_or_404(db, first.id.clone())
            .await
            .unwrap()
            .total,
        12_000
    );
    let both = Invoice::find_many(db, [second.id.clone(), first.id.clone()])
        .await
        .unwrap();
    assert_eq!(both.len(), 2);
    assert_eq!(both[0].id, first.id, "in key order");
    assert!(Invoice::find(db, Ulid::new()).await.unwrap().is_none());

    // Soft deletes, refresh and restore work by key.
    found.delete(db).await.unwrap();
    assert!(Invoice::find(db, first.id.clone()).await.unwrap().is_none());
    found.refresh(db).await.unwrap();
    assert!(found.deleted_at.is_some());
    found.restore(db).await.unwrap();
    assert!(Invoice::find(db, first.id).await.unwrap().is_some());
}

#[renox::test]
async fn string_keys_are_set_by_the_app() {
    let app = app().await;
    let db = app.db();
    let acme = Customer::create(
        db,
        Customer {
            id: "ACME".into(),
            name: "Acme".into(),
        },
    )
    .await
    .unwrap();
    assert_eq!(acme.id, "ACME");

    // Nobody can make up a String key: saving a new one without it fails.
    let mut nameless = Customer {
        name: "No code".into(),
        ..Default::default()
    };
    let err = nameless.save(db).await.unwrap_err();
    assert!(format!("{err:?}").contains("set the `id`"), "{err:?}");

    // `save` with the key set updates; a new row with a set key is `insert`.
    let mut found = Customer::find_or_404(db, "ACME".into()).await.unwrap();
    found.name = "Acme Corp".into();
    found.save(db).await.unwrap();
    let mut globex = Customer {
        id: "GLOBEX".into(),
        name: "Globex".into(),
    };
    globex.insert(db).await.unwrap();
    assert_eq!(Customer::all(db).await.unwrap().len(), 2);
    // Saving an unknown key is a 404, not a silent insert.
    let mut ghost = Customer {
        id: "GHOST".into(),
        name: "Ghost".into(),
    };
    assert!(matches!(ghost.save(db).await, Err(Error::NotFound)));
    // The same key twice is refused by the database.
    assert!(globex.insert(db).await.is_err());
}

