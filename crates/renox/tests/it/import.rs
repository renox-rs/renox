#[renox::test]
async fn an_app_rule_can_veto_an_undo() {
    let app = app().await;
    let report = run(
        &app,
        Import::csv("sku,name,stock\nKEEP,a,1\nGO,b,2\n").undoable(Duration::from_secs(60)),
    )
    .await;
    let batch = report.batch_id.unwrap();
    let veto = Undo::batch(batch)
        .can_undo(|tx, change| {
            Box::pin(async move {
                let used: i64 =
                    sql("SELECT COUNT(*) FROM stock_items WHERE id = ? AND sku = 'KEEP'")
                        .bind_all([change.key().clone()])
                        .scalar(tx)
                        .await?;
                if used > 0 {
                    return Err(Error::BadRequest("KEEP is on an issued document.".into()));
                }
                Ok(())
            })
        })
        .run(app.state())
        .await
        .unwrap_err();
    assert_eq!(format!("{veto}"), "KEEP is on an issued document.");
    // The veto came after GO's row (undone first, newest first): rolled back.
    assert_eq!(skus(&app).await, ["KEEP:1", "GO:2"]);
    // Without the rule it goes through.
    Undo::batch(batch).run(app.state()).await.unwrap();
    assert!(skus(&app).await.is_empty());
}

