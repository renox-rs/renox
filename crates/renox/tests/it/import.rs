#[renox::test]
async fn an_expired_batch_cannot_be_undone() {
    let app = app().await;
    let report = run(
        &app,
        Import::csv("sku,name,stock\nA,a,1\n").undoable(Duration::from_secs(60)),
    )
    .await;
    let batch = report.batch_id.unwrap();
    app.travel(Duration::from_secs(61));
    let err = app
        .at_travelled_time(renox::import::undo(app.state(), batch))
        .await
        .unwrap_err();
    assert_eq!(
        format!("{err}"),
        "This import can no longer be undone: the time allowed for it has passed."
    );
    assert_eq!(skus(&app).await, ["A:1"]);

    // The pruning command forgets finished windows.
    assert_eq!(count(&app, "import_changes").await, 1);
    let pruned = app
        .at_travelled_time(renox::import::prune(app.state(), Duration::ZERO))
        .await
        .unwrap();
    assert_eq!(pruned, 1);
    assert_eq!(count(&app, "import_changes").await, 0);
    assert_eq!(count(&app, "import_batches").await, 0);
}

