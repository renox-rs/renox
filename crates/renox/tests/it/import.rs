#[cfg(feature = "xlsx")]
mod excel {
    use super::*;
    use renox::import::{TemplateColumn, template_xlsx};
    use rust_xlsxwriter::{ExcelDateTime, Format, Workbook};

    /// A workbook with typed cells on two sheets, as a person would make it:
    /// text, whole numbers, decimals, dates, a blank cell, a stray empty row.
    fn workbook() -> Vec<u8> {
        let mut book = Workbook::new();
        let date = Format::new().set_num_format("yyyy-mm-dd");
        let sheet = book.add_worksheet().set_name("Items").unwrap();
        for (c, heading) in ["SKU", "Name", "Stock", "Due"].iter().enumerate() {
            sheet.write_string(0, c as u16, *heading).unwrap();
        }
        sheet.write_string(1, 0, "A-1").unwrap();
        sheet.write_string(1, 1, "Coffee").unwrap();
        sheet.write_number(1, 2, 4.0).unwrap();
        sheet
            .write_datetime_with_format(1, 3, ExcelDateTime::from_ymd(2026, 1, 31).unwrap(), &date)
            .unwrap();
        sheet.write_string(2, 0, "B-2").unwrap();
        sheet.write_string(2, 1, "Tea").unwrap();
        sheet.write_number(2, 2, 9.0).unwrap();
        // Row 4 stays empty; row 5 has a text where a number belongs.
        sheet.write_string(4, 0, "C-3").unwrap();
        sheet.write_string(4, 1, "Milk").unwrap();
        sheet.write_string(4, 2, "lots").unwrap();
        sheet.write_string(5, 1, "Cake").unwrap();
        sheet.write_number(5, 2, 1.0).unwrap();
        let other = book.add_worksheet().set_name("Other").unwrap();
        other.write_string(0, 0, "sku").unwrap();
        other.write_string(0, 1, "name").unwrap();
        other.write_string(0, 2, "stock").unwrap();
        other.write_string(1, 0, "Z-9").unwrap();
        other.write_string(1, 1, "Zinc").unwrap();
        other.write_number(1, 2, 2.5).unwrap();
        book.save_to_buffer().unwrap()
    }

    #[renox::test]
    async fn a_workbook_imports_like_the_equivalent_csv() {
        let xlsx_app = app().await;
        let from_xlsx = run(&xlsx_app, Import::xlsx(workbook())).await;
        let csv_app = app().await;
        let from_csv = run(
            &csv_app,
            Import::csv(
                "SKU,Name,Stock,Due\nA-1,Coffee,4,2026-01-31\nB-2,Tea,9,\n\nC-3,Milk,lots,\n,Cake,1,\n",
            ),
        )
        .await;
        assert_eq!(from_xlsx.imported, 2);
        assert_eq!(problems(&from_xlsx), problems(&from_csv));
        assert_eq!(
            problems(&from_xlsx),
            [
                (5, "The stock must be a number.".to_owned()),
                (6, "The sku field is required.".to_owned()),
            ]
        );
        assert_eq!(skus(&xlsx_app).await, skus(&csv_app).await);
        let coffee = StockItem::query()
            .where_eq("sku", "A-1")
            .first(xlsx_app.db())
            .await
            .unwrap()
            .unwrap();
        assert_eq!(
            coffee.due,
            renox::chrono::NaiveDate::from_ymd_opt(2026, 1, 31)
        );
    }

    #[renox::test]
    async fn a_sheet_is_picked_by_name_and_decimals_stay_decimals() {
        let app = app().await;
        // 2.5 isn't a whole number: the stock rule refuses it like text.
        let report = run(&app, Import::xlsx(workbook()).sheet("Other")).await;
        assert_eq!(report.imported, 0);
        assert_eq!(
            problems(&report),
            [(2, "The stock must be a number.".to_owned())]
        );

        let err = Import::xlsx(workbook())
            .sheet("Missing")
            .run(app.state(), |tx, row: ItemRow| {
                Box::pin(write_item(tx, row))
            })
            .await
            .unwrap_err();
        let Error::Validation(invalid) = err else {
            panic!("a validation error");
        };
        assert_eq!(
            invalid.errors.first("file"),
            Some("The workbook has no sheet called Missing.")
        );
        let not_a_book = Import::xlsx(b"PK\x03\x04 not really")
            .run(app.state(), |tx, row: ItemRow| {
                Box::pin(write_item(tx, row))
            })
            .await
            .unwrap_err();
        let Error::Validation(invalid) = not_a_book else {
            panic!("a validation error");
        };
        assert_eq!(
            invalid.errors.first("file"),
            Some("The file is not a readable Excel workbook (.xlsx).")
        );
    }

    #[renox::test]
    async fn from_upload_picks_csv_or_excel_by_content() {
        let app = app().await;
        let book = Upload::new("items.csv", "text/csv", workbook());
        let from_book = run(&app, Import::from_upload(&book)).await;
        assert_eq!(from_book.imported, 2);
        let text = Upload::new(
            "items.xlsx",
            "application/octet-stream",
            "sku,name,stock\nQ,q,1\n",
        );
        let from_text = run(&app, Import::from_upload(&text)).await;
        assert_eq!(from_text.imported, 1);
    }

    #[renox::test]
    async fn the_template_imports_back_and_the_error_workbook_does_too() {
        let app = app().await;
        let download = template_xlsx(
            "items.xlsx",
            &[
                TemplateColumn::text("sku", "A-1"),
                TemplateColumn::text("name", "Coffee"),
                TemplateColumn::integer("stock", 4),
                TemplateColumn::date(
                    "due",
                    renox::chrono::NaiveDate::from_ymd_opt(2026, 1, 31).unwrap(),
                ),
            ],
        )
        .unwrap();
        let bytes = download_bytes(download).await;
        assert!(bytes.starts_with(b"PK"));
        // Its example row is a valid row, typed cells and all.
        let report = run(&app, Import::xlsx(bytes)).await;
        assert!(report.is_clean(), "{:?}", problems(&report));
        assert_eq!(skus(&app).await, ["A-1:4"]);

        // The whole file with an error column, as a workbook: fix and upload.
        let report = run(&app, Import::csv(CSV)).await;
        let fixed = report
            .error_xlsx("errors.xlsx", ErrorFile::WholeFile)
            .unwrap();
        let again = Import::xlsx(download_bytes(fixed).await)
            .rename("Error", "ignored")
            .run(app.state(), |tx, row: ItemRow| {
                Box::pin(write_item(tx, row))
            })
            .await
            .unwrap();
        // Same rows fail the same way.
        assert_eq!(problems(&again), problems(&report));
    }
}

#[renox::test]
async fn the_whole_file_error_file_adds_a_column_for_every_row() {
    let app = app().await;
    let report = run(&app, Import::csv(CSV)).await;
    let whole = download_text(report.error_csv("errors.csv", ErrorFile::WholeFile)).await;
    let lines: Vec<&str> = whole.trim_end().split("\r\n").collect();
    assert_eq!(lines[0], "\u{feff}sku,name,stock,due,Error");
    assert_eq!(lines.len(), 6);
    assert_eq!(lines[1], "A-1,Coffee,4,2026-01-31,");
    assert!(lines[3].ends_with(",The stock must be a number."));
    assert_eq!(lines[5], "A-1,Again,1,,");
}

#[derive(Deserialize, Validate)]
struct UploadForm {
    #[validate(required)]
    file: Option<Upload>,
    #[serde(default)]
    dry_run: bool,
}

async fn upload(
    State(state): State<AppState>,
    Valid(form): Valid<UploadForm>,
) -> Result<ImportReport> {
    let file = form.file.ok_or(Error::NotFound)?;
    Import::from_upload(&file)
        .dry_run_if(form.dry_run)
        .run(&state, |tx, row: ItemRow| Box::pin(write_item(tx, row)))
        .await
}

