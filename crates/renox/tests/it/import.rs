#[renox::test]
async fn the_kit_offers_a_check_first_box_and_the_report_links_the_error_files() {
    let (app, _dir) = web_app().await;
    let page = app.get("/stock").await;
    page.assert_ok()
        .assert_see(r#"name="dry_run" value="on" checked"#)
        .assert_see(r#"accept=".csv,.xlsx""#);
    // Only the first action asked for the box.
    assert_eq!(page.text().matches(r#"name="dry_run""#).count(), 1);

    // Ticked: the check, which writes nothing and keeps the sheet open.
    let res = app
        .htmx()
        .post_multipart(
            "/stock/import",
            &[("dry_run", "on")],
            &[("file", "stock.csv", CSV.as_bytes())],
        )
        .await;
    res.assert_ok()
        .assert_see(r#"<div class="rx-import-report" data-rx-keep-open>"#)
        .assert_see("Check done, nothing was written: 3 can be imported, 2 rows have errors.")
        .assert_see(r#"download="import-errors.csv""#)
        .assert_see("Download the whole file with an error column")
        .assert_see(r#"<td class="rx-num">4</td><td>The stock must be a number.</td>"#);
    assert_eq!(count(&app, "stock_items").await, 0);

    // A clean check: success, no files, still open.
    let clean = app
        .htmx()
        .post_multipart(
            "/stock/import",
            &[("dry_run", "on")],
            &[("file", "stock.csv", b"sku,name,stock\nOK,ok,1\n")],
        )
        .await;
    clean
        .assert_ok()
        .assert_see("The check found no problems: one row can be imported.");
    assert!(!clean.text().contains("download="));

    // Unticked: the real import (a toast and a refresh when clean).
    let real = app
        .htmx()
        .post_multipart(
            "/stock/import",
            &[],
            &[("file", "stock.csv", b"sku,name,stock\nOK,ok,1\n")],
        )
        .await;
    real.assert_ok().assert_header("hx-refresh", "true");
    assert_eq!(count(&app, "stock_items").await, 1);
}

