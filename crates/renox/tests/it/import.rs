//! Imports beyond CSV (#50): Excel workbooks, the dry run, undo, the error
//! files and the Excel template (`renox::import`).

use std::time::Duration;

use renox::db::{Dialect, capture_queries, sql};
use renox::import::{ErrorFile, Import, ImportReport, ImportTx, Undo};
use renox::prelude::*;
use renox::testing::TestApp;
use serde::{Deserialize, Serialize};

#[derive(Model, Serialize, Deserialize, Default, Clone, Debug)]
#[model(table = "stock_items")]
struct StockItem {
    id: i64,
    sku: String,
    name: String,
    stock: i64,
    due: Option<renox::chrono::NaiveDate>,
    created_at: Option<DateTime>,
    updated_at: Option<DateTime>,
}

/// A model without `updated_at`: undone without the "changed since" check.
#[derive(Model, Serialize, Deserialize, Default, Clone, Debug)]
#[model(table = "stock_labels")]
struct StockLabel {
    id: i64,
    item_id: i64,
    text: String,
}

#[derive(Deserialize, Validate)]
struct ItemRow {
    #[validate(required, max = 20)]
    sku: String,
    #[validate(required)]
    name: String,
    #[validate(required, min = 0)]
    stock: i64,
    #[serde(default)]
    due: Option<renox::chrono::NaiveDate>,
}

/// Inserts the item, or updates the one with the same SKU.
async fn write_item(tx: &mut ImportTx<'_>, row: ItemRow) -> Result {
    let existing = StockItem::query()
        .where_eq("sku", row.sku.as_str())
        .first(&mut *tx)
        .await?;
    match existing {
        Some(mut item) => {
            item.name = row.name;
            item.stock = row.stock;
            item.due = row.due;
            tx.update(&mut item).await
        }
        None => {
            let mut item = StockItem {
                sku: row.sku,
                name: row.name,
                stock: row.stock,
                due: row.due,
                ..Default::default()
            };
            tx.insert(&mut item).await
        }
    }
}

const SQLITE: &str = "CREATE TABLE stock_items (id INTEGER PRIMARY KEY AUTOINCREMENT, sku TEXT NOT NULL UNIQUE, name TEXT NOT NULL, stock BIGINT NOT NULL, due TEXT, created_at TEXT, updated_at TEXT);
    CREATE TABLE stock_labels (id INTEGER PRIMARY KEY AUTOINCREMENT, item_id INTEGER NOT NULL REFERENCES stock_items (id), text TEXT NOT NULL)";
const POSTGRES: &str = "CREATE TABLE stock_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku TEXT NOT NULL UNIQUE, name TEXT NOT NULL, stock BIGINT NOT NULL, due DATE, created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ);
    CREATE TABLE stock_labels (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id BIGINT NOT NULL REFERENCES stock_items (id), text TEXT NOT NULL)";

async fn app() -> TestApp {
    let app = TestApp::new(App::new()).await;
    let schema = match app.db().dialect() {
        Dialect::Postgres => POSTGRES,
        _ => SQLITE,
    };
    for statement in schema.split(';') {
        sql(statement).execute(app.db()).await.unwrap();
    }
    app
}

async fn download_bytes(download: renox::Download) -> Vec<u8> {
    use axum::response::IntoResponse;
    let response = download.into_response();
    axum::body::to_bytes(response.into_body(), usize::MAX)
        .await
        .unwrap()
        .to_vec()
}

async fn download_text(download: renox::Download) -> String {
    String::from_utf8(download_bytes(download).await).unwrap()
}

async fn skus(app: &TestApp) -> Vec<String> {
    StockItem::query()
        .order_by("id")
        .get(app.db())
        .await
        .unwrap()
        .into_iter()
        .map(|i| format!("{}:{}", i.sku, i.stock))
        .collect()
}

async fn count(app: &TestApp, table: &str) -> i64 {
    sql(format!("SELECT COUNT(*) FROM {table}"))
        .scalar(app.db())
        .await
        .unwrap()
}

async fn run(app: &TestApp, import: Import) -> ImportReport {
    import
        .run(app.state(), |tx, row: ItemRow| {
            Box::pin(write_item(tx, row))
        })
        .await
        .unwrap()
}

const CSV: &str = "sku,name,stock,due\nA-1,Coffee,4,2026-01-31\nB-2,Tea,9,\nC-3,Milk,lots,\n,Cake,1,\nA-1,Again,1,\n";

/// Which rows failed and why.
fn problems(report: &ImportReport) -> Vec<(usize, String)> {
    report
        .failed
        .iter()
        .map(|f| (f.row, f.messages().join(" | ")))
        .collect()
}

#[renox::test]
async fn a_dry_run_reports_what_a_real_run_would_and_writes_nothing() {
    let app = app().await;
    let (dry, queries) = capture_queries(run(&app, Import::csv(CSV).dry_run())).await;
    assert!(dry.dry_run && dry.batch_id.is_none());
    assert_eq!(dry.imported, 3);
    assert_eq!(count(&app, "stock_items").await, 0, "rolled back");
    // The writer really ran (its INSERTs are in the log), and nothing was
    // recorded for undo.
    assert!(
        queries
            .iter()
            .any(|q| q.contains("INSERT INTO \"stock_items\""))
    );
    assert!(!queries.iter().any(|q| q.contains("import_batches")));
    assert_eq!(
        dry.summary(),
        "Check done, nothing was written: 3 can be imported, 2 rows have errors."
    );

    let real = run(&app, Import::csv(CSV)).await;
    assert_eq!(real.imported, 3);
    assert_eq!(problems(&dry), problems(&real));
    // The repeat of A-1 on row 6 updated the row row 2 inserted, in both runs.
    assert_eq!(skus(&app).await, ["A-1:1", "B-2:9"]);
    assert_eq!(
        problems(&real),
        [
            (4, "The stock must be a number.".to_owned()),
            (5, "The sku field is required.".to_owned()),
        ]
    );
}

#[renox::test]
async fn a_dry_run_sees_the_writes_of_its_own_earlier_rows() {
    let app = app().await;
    // The closure counts the rows it can see: the earlier rows of the same
    // run are there while it runs, and gone after.
    let seen = std::sync::Arc::new(std::sync::Mutex::new(Vec::new()));
    let log = seen.clone();
    let report = Import::csv("sku,name,stock\nA,a,1\nB,b,2\nC,c,3\n")
        .dry_run()
        .run(app.state(), move |tx, row: ItemRow| {
            let log = log.clone();
            Box::pin(async move {
                let rows: i64 = sql("SELECT COUNT(*) FROM stock_items")
                    .scalar(&mut *tx)
                    .await?;
                log.lock().unwrap().push(rows);
                write_item(tx, row).await
            })
        })
        .await
        .unwrap();
    assert_eq!(report.imported, 3);
    assert_eq!(*seen.lock().unwrap(), [0, 1, 2]);
    assert_eq!(count(&app, "stock_items").await, 0);
}

#[renox::test]
async fn an_undoable_import_is_undone_with_its_inserts_and_updates() {
    let app = app().await;
    let mut old = StockItem {
        sku: "A-1".into(),
        name: "Old coffee".into(),
        stock: 1,
        due: renox::chrono::NaiveDate::from_ymd_opt(2025, 5, 5),
        ..Default::default()
    };
    old.insert(app.db()).await.unwrap();
    let before = StockItem::find_or_404(app.db(), old.id).await.unwrap();

    let report = run(
        &app,
        Import::csv("sku,name,stock,due\nA-1,Coffee,4,2026-01-31\nB-2,Tea,9,\n")
            .undoable(Duration::from_secs(3600)),
    )
    .await;
    assert!(report.is_clean());
    let batch = report.batch_id.expect("a batch");
    assert_eq!(skus(&app).await, ["A-1:4", "B-2:9"]);

    let undone = renox::import::undo(app.state(), batch).await.unwrap();
    assert_eq!((undone.deleted, undone.restored), (1, 1));
    // The updated row is exactly as it was, timestamps and date included.
    let after = StockItem::find_or_404(app.db(), old.id).await.unwrap();
    assert_eq!(
        (&after.name, after.stock, after.due, after.updated_at),
        (&before.name, before.stock, before.due, before.updated_at)
    );
    assert_eq!(skus(&app).await, ["A-1:1"]);

    // Once only.
    let again = renox::import::undo(app.state(), batch).await.unwrap_err();
    assert_eq!(format!("{again}"), "This import was already undone.");
    assert_eq!(skus(&app).await, ["A-1:1"]);
}

#[renox::test]
async fn an_import_that_is_not_undoable_or_dry_leaves_no_batch() {
    let app = app().await;
    let plain = run(&app, Import::csv("sku,name,stock\nA,a,1\n")).await;
    assert!(plain.batch_id.is_none());
    let dry = run(
        &app,
        Import::csv("sku,name,stock\nB,b,1\n")
            .undoable(Duration::from_secs(60))
            .dry_run(),
    )
    .await;
    assert!(dry.batch_id.is_none());
    // Undoable, but nothing was written through the ImportTx: no batch.
    let none = Import::csv("sku,name,stock\nC,c,1\n")
        .undoable(Duration::from_secs(60))
        .run(app.state(), |tx, row: ItemRow| {
            Box::pin(async move {
                sql("INSERT INTO stock_items (sku, name, stock) VALUES (?, ?, ?)")
                    .bind(row.sku)
                    .bind(row.name)
                    .bind(row.stock)
                    .execute(tx)
                    .await?;
                Ok(())
            })
        })
        .await
        .unwrap();
    assert_eq!(none.imported, 1);
    assert!(none.batch_id.is_none());
    assert_eq!(count(&app, "import_batches").await, 0);
    assert!(renox::import::undo(app.state(), 99).await.is_err());
}

#[renox::test]
async fn undo_refuses_when_a_row_changed_or_vanished_and_changes_nothing() {
    let app = app().await;
    let report = run(
        &app,
        Import::csv("sku,name,stock\nA,a,1\nB,b,2\n").undoable(Duration::from_secs(3600)),
    )
    .await;
    let batch = report.batch_id.unwrap();

    let mut b = StockItem::query()
        .where_eq("sku", "B")
        .first(app.db())
        .await
        .unwrap()
        .unwrap();
    b.name = "renamed by someone".into();
    b.save(app.db()).await.unwrap();
    let err = renox::import::undo(app.state(), batch).await.unwrap_err();
    assert_eq!(
        format!("{err}"),
        format!(
            "The import can't be undone: the stock_items row {} was changed after it.",
            b.id
        )
    );
    assert_eq!(skus(&app).await, ["A:1", "B:2"], "nothing was undone");

    b.force_delete(app.db()).await.unwrap();
    let err = renox::import::undo(app.state(), batch).await.unwrap_err();
    assert!(format!("{err}").contains("was deleted after it"), "{err}");
    assert_eq!(skus(&app).await, ["A:1"]);
}

