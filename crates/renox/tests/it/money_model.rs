//! `#[model(money)]` and `#[model(money(currency = "…"))]` (#45): a `Money`
//! field stored as an amount column plus a currency column.

use renox::db::Migration;
use renox::money::Money;
use renox::prelude::*;
use renox::testing::TestApp;

const SCHEMA: Migration = Migration::new("20300101000000_money_model", "", None)
    .sqlite(
        "CREATE TABLE orders (id INTEGER PRIMARY KEY AUTOINCREMENT, total BIGINT NOT NULL,
         total_currency TEXT NOT NULL, refund BIGINT, refund_currency TEXT);
     CREATE TABLE quotes (id INTEGER PRIMARY KEY AUTOINCREMENT, subtotal BIGINT NOT NULL,
         currency TEXT NOT NULL, tax BIGINT NOT NULL, total BIGINT NOT NULL);",
        None,
    )
    .postgres(
        "CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, total BIGINT NOT NULL,
         total_currency TEXT NOT NULL, refund BIGINT, refund_currency TEXT);
     CREATE TABLE quotes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, subtotal BIGINT NOT NULL,
         currency TEXT NOT NULL, tax BIGINT NOT NULL, total BIGINT NOT NULL);",
        None,
    );

#[derive(Model, serde::Serialize, Debug, Clone, PartialEq)]
#[model(table = "orders")]
struct Order {
    id: i64,
    #[model(money)]
    total: Money,
    #[model(money)]
    refund: Option<Money>,
}

#[derive(Model, serde::Serialize, Debug, Clone, PartialEq)]
#[model(table = "quotes")]
struct Quote {
    id: i64,
    #[model(money(currency = "currency"))]
    subtotal: Money,
    #[model(money(currency = "currency"))]
    tax: Money,
    #[model(money(currency = "currency"))]
    total: Money,
}

#[derive(FromRow, Debug, PartialEq)]
struct Summary {
    #[row(money)]
    total: Money,
    #[row(money(currency = "total_currency"))]
    refund: Option<Money>,
}

fn order(total: Money, refund: Option<Money>) -> Order {
    Order {
        id: 0,
        total,
        refund,
    }
}

#[test]
fn columns_and_typed_constants_cover_the_pair() {
    use renox::db::Model as _;
    assert_eq!(
        Order::COLUMNS,
        &["id", "total", "total_currency", "refund", "refund_currency"]
    );
    assert_eq!(
        Quote::COLUMNS,
        &["id", "subtotal", "currency", "tax", "total"]
    );
    let _: renox::db::Col<Order, i64> = Order::TOTAL;
    let _: renox::db::Col<Order, String> = Order::TOTAL_CURRENCY;
    let _: renox::db::Col<Order, Option<i64>> = Order::REFUND;
    let _: renox::db::Col<Quote, String> = Quote::CURRENCY;
}

#[renox::test]
async fn a_pair_round_trips_with_an_optional_money() {
    let app = TestApp::new(App::new().migrations(&[SCHEMA])).await;
    let db = app.db();
    let a = Order::create(db, order(Money::kwd(12_345), Some(Money::kwd(500))))
        .await
        .unwrap();
    let b = Order::create(db, order(Money::jpy(1_250), None))
        .await
        .unwrap();
    let a = Order::find_or_404(db, a.id).await.unwrap();
    assert_eq!(a.total, Money::kwd(12_345));
    assert_eq!(a.refund, Some(Money::kwd(500)));
    let b = Order::find_or_404(db, b.id).await.unwrap();
    assert_eq!(b.total, Money::jpy(1_250));
    assert_eq!(b.refund, None);

    // Saving a loaded record updates both columns and clears the optional pair together.
    let mut a = a;
    a.total = Money::usd(99);
    a.refund = None;
    a.save(db).await.unwrap();
    let a = Order::find_or_404(db, a.id).await.unwrap();
    assert_eq!((a.total, a.refund), (Money::usd(99), None));

    // The typed constant filters on the minor amount.
    let big = Order::query()
        .where_(Order::TOTAL.gt(1_000))
        .get(db)
        .await
        .unwrap();
    assert_eq!(big.len(), 1);
    assert_eq!(big[0].total, Money::jpy(1_250));
}

#[renox::test]
async fn several_fields_share_one_currency_column() {
    let app = TestApp::new(App::new().migrations(&[SCHEMA])).await;
    let db = app.db();
    let q = Quote::create(
        db,
        Quote {
            id: 0,
            subtotal: Money::aed(10_000),
            tax: Money::aed(500),
            total: Money::aed(10_500),
        },
    )
    .await
    .unwrap();
    let q = Quote::find_or_404(db, q.id).await.unwrap();
    assert_eq!(q.subtotal, Money::aed(10_000));
    assert_eq!(q.tax, Money::aed(500));
    assert_eq!(q.total, Money::aed(10_500));
}

#[renox::test]
async fn from_row_reads_money_pairs() {
    let app = TestApp::new(App::new()).await;
    let row = renox::db::sql("SELECT 1250 AS total, 'USD' AS total_currency, 300 AS refund")
        .fetch_as::<Summary>(app.db())
        .await
        .unwrap();
    assert_eq!(
        row,
        vec![Summary {
            total: Money::usd(1250),
            refund: Some(Money::usd(300))
        }]
    );
    // A set currency with a NULL amount is an error, not a silent `None`.
    let row = renox::db::sql("SELECT 1250 AS total, 'USD' AS total_currency, NULL AS refund")
        .fetch_as::<Summary>(app.db())
        .await;
    assert!(
        row.is_err(),
        "the shared currency is set, the amount is not"
    );
}
