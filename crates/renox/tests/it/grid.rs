/// The cells of `column` on the page, as text.
fn cells(html: &str, column: &str) -> Vec<String> {
    html.split(&format!("<td data-col=\"{column}\""))
        .skip(1)
        .filter_map(|cell| {
            let text = cell.split_once('>')?.1.split_once("</td>")?.0;
            Some(text_of(text))
        })
        .collect()
}

