#[renox::test]
async fn the_advanced_filter_combines_rules() {
    let (app, _views) = pets_app().await;
    let names = |q: &'static str| {
        let app = &app;
        async move { cells(&app.get(&format!("/pets?state=1&{q}")).await.text(), "name") }
    };
    assert_eq!(
        names("r.0.c=weight&r.0.o=gt&r.0.v=5").await,
        ["Momo", "Rex"]
    );
    assert_eq!(
        names("r.0.c=weight&r.0.o=gt&r.0.v=5&r.1.c=owner&r.1.o=equals&r.1.v=anna").await,
        ["Momo"],
        "all by default"
    );
    assert_eq!(
        names("match=any&r.0.c=weight&r.0.o=lt&r.0.v=4&r.1.c=owner&r.1.o=equals&r.1.v=ben").await,
        ["Rex", "Stray"]
    );
    assert_eq!(names("r.0.c=owner&r.0.o=empty").await, ["Stray"]);
    assert_eq!(
        names("r.0.c=name&r.0.o=not_contains&r.0.v=k").await,
        ["Momo", "Rex", "Stray"]
    );
    assert_eq!(
        names("r.0.c=born&r.0.o=before&r.0.v=2024-05-10").await,
        ["Kiki"]
    );
    assert_eq!(
        names("r.0.c=born&r.0.o=on&r.0.v=2024-05-10").await,
        ["Momo"]
    );
    assert_eq!(
        names("r.0.c=born&r.0.o=after&r.0.v=2024-05-10").await,
        ["Rex"]
    );
    // Bad rules are dropped, not errors.
    for q in [
        "r.0.c=weight&r.0.o=gt&r.0.v=heavy",
        "r.0.c=nope&r.0.o=eq&r.0.v=1",
        "r.0.c=weight&r.0.o=like&r.0.v=1",
        "r.99.c=weight&r.99.o=gt&r.99.v=1",
    ] {
        assert_eq!(names(q).await.len(), 4, "{q}");
    }
    let page = app.get("/pets?state=1&r.0.c=weight&r.0.o=gt&r.0.v=5").await;
    page.assert_see("Advanced filter: 1 rule")
        .assert_see(r#"name="r.0.v" value="5""#)
        .assert_see("&quot;poll&quot;:20");
}

