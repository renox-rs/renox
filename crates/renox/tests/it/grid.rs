fn grid() -> Grid {
    Grid::new("orders")
        .title("Orders")
        .column(Column::text("number", "Order").frozen().mobile())
        .column(
            Column::select("status", "Status", [("new", "New"), ("paid", "Paid")]).under(["State"]),
        )
        .column(Column::bool("paid", "Paid").under(["State"]))
        .column(Column::tags(
            "tags",
            "Tags",
            [("online", "Online"), ("promo", "Promo")],
        ))
        .column(Column::money("total", "Total"))
        .column(Column::date("ordered_on", "Ordered"))
        .column(Column::datetime("placed_at", "Placed").hidden())
        .column(Column::custom("chart", "Chart"))
        .per_page(10)
        .sort_by("-total")
}

struct Orders;

impl Module for Orders {
    fn name(&self) -> &'static str {
        "orders"
    }

    fn routes(&self) -> Routes {
        Routes::new()
            .get("/orders", index)
            .get("/totals", totals)
            .get("/exports", exports)
            .get("/exports-detail", exports_detail)
            .get("/plain", plain)
            // A grid in a group: its links keep the group's prefix.
            .group("/back", "back.", Routes::new().get("/exports", exports))
    }
}

async fn index(request: GridRequest) -> Result<View> {
    let page = grid()
        .page(GridOrder::query(), &request)
        .await?
        .extend(|order| json!({ "points": [1, order.total % 7, 3] }));
    Ok(view("orders.html", context! { orders => page }))
}

/// M27c: the same grid with its export menu.
async fn exports(request: GridRequest) -> Result<Response> {
    let grid = grid().exports();
    if let Some(file) = grid.export(GridOrder::query(), &request).await? {
        return Ok(file);
    }
    let page = grid.page(GridOrder::query(), &request).await?;
    Ok(view("orders.html", context! { orders => page }).into_response())
}

/// #255: a grid whose exports show a moment in APP_TIMEZONE, numbers with
/// decimals and yes/no.
async fn exports_detail(request: GridRequest) -> Result<Response> {
    let grid = Grid::new("detail")
        .column(Column::text("number", "Order"))
        .column(Column::datetime("placed_at", "Placed"))
        .column(Column::number("total", "Total").decimals(2))
        .column(Column::bool("paid", "Paid"))
        .sort_by("number")
        .exports();
    match grid.export(GridOrder::query(), &request).await? {
        Some(file) => Ok(file),
        None => Ok("no export".into_response()),
    }
}

/// `Grid::filter` for figures over every filtered row.
async fn totals(State(state): State<AppState>, request: GridRequest) -> Result<String> {
    let sum: i64 = grid()
        .filter(GridOrder::query(), &request)
        .sum(&state.db, "total")
        .await?;
    Ok(sum.to_string())
}

