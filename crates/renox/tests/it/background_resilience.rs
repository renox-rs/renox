#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn job_longer_than_the_reservation_runs_once() {
    let k = kernel().await;
    let (stop, stopped) = tokio::sync::watch::channel(false);
    let worker = tokio::spawn(k.worker(Vec::new()).run(1, stopped));
    k.state().dispatch(LongJob).await.unwrap();
    assert!(wait_for(k.db(), "long start", 5).await);
    // Simulate 16 minutes passing while the (legal, TIMEOUT = 30 min) job runs.
    renox::db::sql("UPDATE jobs SET reserved_at = reserved_at - 960")
        .execute(k.db())
        .await
        .unwrap();
    let second = k.worker(Vec::new());
    let ran = tokio::spawn(async move { second.run_next().await });
    tokio::time::sleep(Duration::from_secs(3)).await;
    let _ = ran.await;
    stop.send(true).unwrap();
    let _ = worker.await;
    let starts = logged(k.db())
        .await
        .into_iter()
        .filter(|m| m.starts_with("long start"))
        .collect::<Vec<_>>();
    eprintln!("TIMEOUT > RESERVATION: starts = {starts:?}");
    assert_eq!(
        starts.len(),
        1,
        "a running job was picked up by a second worker"
    );
}

