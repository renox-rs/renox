#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn dispatch_in_a_rolled_back_transaction_is_dropped() {
    let dir = tempfile::tempdir().unwrap();
    let mut results = Vec::new();
    for (label, cfg) in [
        ("default", config()),
        ("file-sqlite", {
            let mut c = config();
            c.database_url = format!("sqlite://{}/t.db", dir.path().display());
            c
        }),
    ] {
        let k = kernel_cfg(cfg).await;
        let mut tx = k.db().begin().await.unwrap();
        renox::db::sql("INSERT INTO log (message) VALUES ('order row')")
            .execute(&mut tx)
            .await
            .unwrap();
        let started = Instant::now();
        let dispatched = tokio::time::timeout(
            Duration::from_secs(8),
            k.state().queue.dispatch_in(
                &mut tx,
                Greet {
                    name: "receipt".into(),
                },
            ),
        )
        .await;
        let took = started.elapsed();
        tx.rollback().await.unwrap();
        let queued = k.state().queue.pending().await.unwrap();
        eprintln!(
            "dispatch inside tx ({label}, {:?}): {} after {took:?}; after rollback jobs queued = {queued}",
            k.db().dialect(),
            match &dispatched {
                Err(_) => "HUNG".to_owned(),
                Ok(Ok(id)) => format!("ok id {id}"),
                Ok(Err(e)) => format!("error {e:?}"),
            }
        );
        results.push((label, matches!(dispatched, Ok(Ok(_))), queued));
    }
    for (label, ok, queued) in results {
        assert!(
            ok,
            "{label}: dispatch while a transaction is open failed/hung"
        );
        assert_eq!(
            queued, 0,
            "{label}: the job outlives the rolled-back transaction (no afterCommit)"
        );
    }
}

