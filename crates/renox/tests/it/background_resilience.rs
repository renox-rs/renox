#[derive(Default)]
struct Smtp {
    commands: Vec<String>,
    data: Vec<String>,
}

/// A minimal SMTP server that records what it's sent.
async fn fake_smtp() -> (u16, Arc<Mutex<Smtp>>) {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let port = listener.local_addr().unwrap().port();
    let seen = Arc::new(Mutex::new(Smtp::default()));
    let record = seen.clone();
    tokio::spawn(async move {
        while let Ok((stream, _)) = listener.accept().await {
            let record = record.clone();
            tokio::spawn(async move {
                let (read, mut write) = stream.into_split();
                let mut lines = BufReader::new(read).lines();
                write.write_all(b"220 fake ESMTP\r\n").await.ok();
                let mut in_data = false;
                let mut data = String::new();
                while let Ok(Some(line)) = lines.next_line().await {
                    if in_data {
                        if line == "." {
                            in_data = false;
                            record.lock().unwrap().data.push(std::mem::take(&mut data));
                            write.write_all(b"250 queued\r\n").await.ok();
                        } else {
                            data.push_str(&line);
                            data.push('\n');
                        }
                        continue;
                    }
                    record.lock().unwrap().commands.push(line.clone());
                    let upper = line.to_ascii_uppercase();
                    let reply: &[u8] = if upper.starts_with("EHLO") || upper.starts_with("HELO") {
                        b"250 fake\r\n"
                    } else if upper.starts_with("DATA") {
                        in_data = true;
                        b"354 go ahead\r\n"
                    } else if upper.starts_with("QUIT") {
                        write.write_all(b"221 bye\r\n").await.ok();
                        break;
                    } else {
                        b"250 ok\r\n"
                    };
                    write.write_all(reply).await.ok();
                }
            });
        }
    });
    (port, seen)
}

fn smtp_config(port: u16) -> Config {
    let mut c = config();
    c.mail.mailer = renox::mail::MailDriver::Smtp;
    c.mail.host = "127.0.0.1".into();
    c.mail.port = Some(port);
    c.mail.encryption = renox::mail::MailEncryption::None;
    c.mail.from_address = "app@example.com".into();
    c
}

#[renox::test(flavor = "multi_thread", worker_threads = 4)]
