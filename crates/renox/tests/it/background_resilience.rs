async fn log(state: &AppState, message: &str) -> Result {
    renox::db::sql("INSERT INTO log (message) VALUES (?)")
        .bind(message.to_owned())
        .execute(&state.db)
        .await?;
    Ok(())
}

async fn logged(db: &Db) -> Vec<String> {
    renox::db::sql("SELECT message FROM log ORDER BY id")
        .scalars(db)
        .await
        .unwrap()
}

async fn create_log(db: &Db) {
    renox::db::sql(match db.dialect() {
        Dialect::Sqlite => "CREATE TABLE log (id INTEGER PRIMARY KEY, message TEXT NOT NULL)",
        Dialect::Postgres => {
            "CREATE TABLE log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, message TEXT NOT NULL)"
        }
    })
    .execute(db)
    .await
    .unwrap();
}

#[derive(Serialize, Deserialize)]
struct Greet {
    name: String,
}
impl Job for Greet {
    const NAME: &'static str = "probe-greet";
    async fn handle(self, ctx: JobContext) -> Result {
        log(&ctx.state, &format!("hello {}", self.name)).await
    }
}

#[derive(Serialize, Deserialize)]
struct Panicky;
impl Job for Panicky {
    const NAME: &'static str = "probe-panicky";
    const MAX_ATTEMPTS: u32 = 2;
    fn backoff(_: u32) -> Duration {
        Duration::ZERO
    }
    async fn handle(self, ctx: JobContext) -> Result {
        log(&ctx.state, &format!("panicky attempt {}", ctx.attempt)).await?;
        panic!("the job panicked");
    }
}

/// Logs its `failed` hook, to see that a crashed last attempt runs it.
#[derive(Serialize, Deserialize)]
struct Remembered;
impl Job for Remembered {
    const NAME: &'static str = "probe-remembered";
    async fn handle(self, ctx: JobContext) -> Result {
        log(&ctx.state, "remembered ran").await
    }
    async fn failed(self, ctx: JobContext, error: String) {
        let _ = log(&ctx.state, &format!("failed hook: {error}")).await;
    }
}

/// Takes longer than it's allowed to be reserved (TIMEOUT > RESERVATION = 15 min).
#[derive(Serialize, Deserialize)]
struct LongJob;
impl Job for LongJob {
    const NAME: &'static str = "probe-long";
    const TIMEOUT: Duration = Duration::from_secs(30 * 60);
    async fn handle(self, ctx: JobContext) -> Result {
        log(&ctx.state, &format!("long start (attempt {})", ctx.attempt)).await?;
        tokio::time::sleep(Duration::from_secs(2)).await;
        log(&ctx.state, "long end").await
    }
}

async fn kernel_cfg(config: Config) -> Kernel {
    let k = App::with_config(config)
        .job::<Greet>()
        .job::<Panicky>()
        .job::<LongJob>()
        .job::<Remembered>()
        .boot()
        .await
        .unwrap();
    k.migrate().await.unwrap();
    create_log(k.db()).await;
    k
}

async fn kernel() -> Kernel {
    kernel_cfg(config()).await
}

async fn wait_for(db: &Db, what: &str, secs: u64) -> bool {
    let until = Instant::now() + Duration::from_secs(secs);
    while Instant::now() < until {
        if logged(db).await.iter().any(|m| m.contains(what)) {
            return true;
        }
        tokio::time::sleep(Duration::from_millis(50)).await;
    }
    false
}

async fn scalar(db: &Db, sql: &str) -> i64 {
    renox::db::sql(sql).scalar(db).await.unwrap()
}

