#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn worker_survives_a_panicking_job() {
    let k = kernel().await;
    let (stop, stopped) = tokio::sync::watch::channel(false);
    let worker = tokio::spawn(k.worker(Vec::new()).run(1, stopped));
    k.state().dispatch(Panicky).await.unwrap();
    assert!(wait_for(k.db(), "panicky attempt 1", 5).await);
    tokio::time::sleep(Duration::from_millis(300)).await;
    k.state()
        .dispatch(Greet {
            name: "after".into(),
        })
        .await
        .unwrap();
    let ran = wait_for(k.db(), "hello after", 4).await;
    let jobs: Vec<String> = renox::db::sql(
        "SELECT job || ' attempts=' || attempts || ' reserved=' || COALESCE(CAST(reserved_at AS TEXT), 'null') FROM jobs",
    )
    .scalars(k.db())
    .await
    .unwrap();
    let failed = scalar(k.db(), "SELECT COUNT(*) FROM failed_jobs").await;
    eprintln!(
        "after a panicking job: next job ran = {ran}; jobs = {jobs:?}; failed_jobs = {failed}; log = {:?}",
        logged(k.db()).await
    );
    stop.send(true).unwrap();
    let joined = tokio::time::timeout(Duration::from_secs(3), worker).await;
    eprintln!("worker shutdown after panic: {joined:?}");
    assert!(
        ran,
        "the worker loop died with the panicking job; later jobs never run"
    );
}

