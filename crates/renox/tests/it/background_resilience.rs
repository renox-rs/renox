async fn two_workers(k: &Kernel, jobs: usize) {
    for i in 0..jobs {
        k.state()
            .dispatch(Greet {
                name: format!("j{i}"),
            })
            .await
            .unwrap();
    }
    let (stop, stopped) = tokio::sync::watch::channel(false);
    let a = tokio::spawn(k.worker(Vec::new()).run(4, stopped.clone()));
    let b = tokio::spawn(k.worker(Vec::new()).run(4, stopped));
    let until = Instant::now() + Duration::from_secs(60);
    while Instant::now() < until && k.state().queue.pending().await.unwrap_or(1) > 0 {
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    stop.send(true).unwrap();
    let _ = (a.await, b.await);
    let log = logged(k.db()).await;
    let unique: std::collections::HashSet<_> = log.iter().collect();
    let failed = scalar(k.db(), "SELECT COUNT(*) FROM failed_jobs").await;
    eprintln!(
        "2 workers x 4 loops on {:?}: ran {} ({} unique) of {jobs}; pending {}; failed {failed}",
        k.db().dialect(),
        log.len(),
        unique.len(),
        k.state().queue.pending().await.unwrap()
    );
    assert_eq!((log.len(), unique.len(), failed), (jobs, jobs, 0));
}

