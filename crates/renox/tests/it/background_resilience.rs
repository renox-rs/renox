// ---------------------------------------------------------------- 10. webhooks

static HANDLED: AtomicUsize = AtomicUsize::new(0);
static PANIC_NEXT: AtomicBool = AtomicBool::new(false);
static LAST_PAYLOAD: Mutex<Vec<u8>> = Mutex::new(Vec::new());

/// Unsigned provider whose event id is in a header (like X-GitHub-Delivery).
struct Hook;
impl Webhook for Hook {
    const PROVIDER: &'static str = "probe-hook";
    fn verify(request: &WebhookRequest, _: &AppState) -> Result {
        renox::webhook::ensure(request.header("x-token") == Some("t"))
    }
    fn event_id(request: &WebhookRequest) -> Result<String> {
        Ok(request.header("x-event-id").unwrap_or_default().to_owned())
    }
    async fn handle(call: WebhookCall, _: JobContext) -> Result {
        HANDLED.fetch_add(1, Ordering::SeqCst);
        *LAST_PAYLOAD.lock().unwrap() = call.payload.clone();
        if PANIC_NEXT.swap(false, Ordering::SeqCst) {
            panic!("webhook handler panicked");
        }
        Ok(())
    }
}

struct Hooks;
impl Module for Hooks {
    fn name(&self) -> &'static str {
        "hooks"
    }
    fn routes(&self) -> Routes {
        Routes::new().webhook::<Hook>("/wh")
    }
    fn register(&self, app: &mut Registry) {
        app.webhook::<Hook>();
    }
}

async fn hook_app() -> TestApp {
    TestApp::new(App::new().module(Hooks)).await
}

async fn deliver(
    app: &TestApp,
    id: &str,
    body: impl Into<Vec<u8>>,
) -> renox::testing::TestResponse {
    app.request()
        .without_csrf()
        .header("x-token", "t")
        .header("x-event-id", id)
        .post_body("/wh", "application/octet-stream", body)
        .await
}

/// One test so the statics aren't shared between parallel tests.
#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn webhook_edge_cases() {
    let app = Arc::new(hook_app().await);

    // Huge body.
    let r = deliver(&app, "big", vec![b'x'; 11 * 1024 * 1024]).await;
    eprintln!("11 MB webhook body -> {}", r.status);
    assert_eq!(r.status, StatusCode::PAYLOAD_TOO_LARGE);

    // Invalid UTF-8 body: stored exactly?
    let raw = b"{\"amount\":\"\xff\xfe\"}".to_vec();
    deliver(&app, "utf8", raw.clone()).await.assert_ok();
    app.run_jobs().await;
    let stored = LAST_PAYLOAD.lock().unwrap().clone();
    eprintln!(
        "invalid UTF-8 body: stored bytes equal = {}; stored = {:?}",
        stored == raw,
        String::from_utf8_lossy(&stored)
    );
    let utf8_exact = stored == raw;

    // A NUL byte in the body.
    let r = deliver(&app, "nul", b"{\"a\":\"\x00\"}".to_vec()).await;
    eprintln!("body with a raw NUL byte -> {}", r.status);
    let nul_ok = r.status == StatusCode::OK;

    // Replay after processed.
    app.run_jobs().await;
    let before = HANDLED.load(Ordering::SeqCst);
    deliver(&app, "once", "{}").await.assert_ok();
    app.run_jobs().await;
    let replay = deliver(&app, "once", "{}").await;
    app.run_jobs().await;
    assert_eq!(replay.text(), "already received");
    assert_eq!(
        HANDLED.load(Ordering::SeqCst),
        before + 1,
        "replay not processed again"
    );

    // webhook:retry on a processed call.
    let id: i64 = renox::db::sql("SELECT id FROM webhook_calls WHERE event_id = 'once'")
        .scalar(app.db())
        .await
        .unwrap();
    let retried = renox::webhook::retry(app.state(), id).await.unwrap();
    app.run_jobs().await;
    eprintln!(
        "webhook:retry on a processed call: accepted={retried}; handled again = {}",
        HANDLED.load(Ordering::SeqCst) == before + 2
    );

    // Very long event id.
    let long = "e".repeat(10_000);
    let r = deliver(&app, &long, "{}").await;
    eprintln!("10 000-char event id -> {}", r.status);
    let long_ok = r.status == StatusCode::OK;

    // Concurrent identical deliveries.
    let mut tasks = Vec::new();
    for _ in 0..20 {
        let app = app.clone();
        tasks.push(tokio::spawn(async move {
            deliver(&app, "same", "{}").await.status
        }));
    }
    let mut statuses = Vec::new();
    for t in tasks {
        statuses.push(t.await.unwrap().as_u16());
    }
    let rows: i64 = renox::db::sql("SELECT COUNT(*) FROM webhook_calls WHERE event_id = 'same'")
        .scalar(app.db())
        .await
        .unwrap();
    eprintln!("20 concurrent identical deliveries: statuses {statuses:?}; rows {rows}");
    assert_eq!(rows, 1);
    assert!(statuses.iter().all(|s| *s == 200));

    // Handler panic.
    app.run_jobs().await;
    PANIC_NEXT.store(true, Ordering::SeqCst);
    deliver(&app, "panics", "{}").await.assert_ok();
    let k = app.clone();
    let joined = tokio::spawn(async move { k.kernel().run_jobs().await }).await;
    let status: String =
        renox::db::sql("SELECT status FROM webhook_calls WHERE event_id = 'panics'")
            .scalar(app.db())
            .await
            .unwrap();
    let job: Option<String> = renox::db::sql(
        "SELECT 'attempts=' || attempts || ' reserved=' || COALESCE(CAST(reserved_at AS TEXT),'null') FROM jobs",
    )
    .scalar_optional(app.db())
    .await
    .unwrap();
    eprintln!(
        "webhook handler panic: run_jobs {}; call status = {status}; job = {job:?}",
        if joined.is_err() {
            "PANICKED"
        } else {
            "returned"
        }
    );

    assert!(
        utf8_exact,
        "invalid UTF-8 is replaced (U+FFFD): the handler can't re-verify or decode the original bytes"
    );
    assert!(nul_ok, "a NUL byte in the body is refused by the database");
    assert!(long_ok, "a long event id is refused by the database");
    assert_eq!(
        status, "failed",
        "a panicking handler leaves the call `received` forever"
    );
}

#[renox::test]
async fn webhook_long_random_event_id() {
    let app = hook_app().await;
    // 10 000 non-repeating characters (a long provider id; doesn't compress).
    let mut x: u64 = 0x9E37_79B9_7F4A_7C15;
    let id: String = (0..10_000)
        .map(|_| {
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            char::from(b'a' + (x % 26) as u8)
        })
        .collect();
    let r = deliver(&app, &id, "{}").await;
    eprintln!(
        "10 000-char random event id on {:?} -> {} {}",
        app.db().dialect(),
        r.status,
        r.text()
    );
    assert_eq!(r.status, StatusCode::OK);
}
