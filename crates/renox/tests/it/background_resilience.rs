static SCHED_PANIC: AtomicUsize = AtomicUsize::new(0);
static SCHED_ERR: AtomicUsize = AtomicUsize::new(0);
static SCHED_SLOW: AtomicUsize = AtomicUsize::new(0);

#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn scheduler_task_that_panics_keeps_running() {
    let dir = tempfile::tempdir().unwrap();
    let port = std::net::TcpListener::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
        .port();
    let cfg = {
        let mut c = config();
        c.database_url = format!("sqlite://{}/s.db", dir.path().display());
        c.port = port;
        c.scheduler = true;
        c.storage_path = dir.path().join("storage");
        c
    };
    let k = App::with_config(cfg.clone()).boot().await.unwrap();
    k.migrate().await.unwrap();
    k.db().close().await;
    let app = App::with_config(cfg).schedule(|s| {
        s.every(Duration::from_secs(1), "probe-panic", |_| async {
            SCHED_PANIC.fetch_add(1, Ordering::SeqCst);
            panic!("scheduled task panicked");
        });
        s.every(Duration::from_secs(1), "probe-err", |_| async {
            SCHED_ERR.fetch_add(1, Ordering::SeqCst);
            Err(Error::BadRequest("task failed".into()))
        });
        s.every(Duration::from_secs(1), "probe-slow", |_| async {
            SCHED_SLOW.fetch_add(1, Ordering::SeqCst);
            tokio::time::sleep(Duration::from_millis(2500)).await;
            Ok(())
        });
    });
    let server = tokio::spawn(app.serve());
    // Wait for enough runs (slow machines take longer), up to 30 s.
    let started = Instant::now();
    while started.elapsed() < Duration::from_secs(30)
        && (SCHED_PANIC.load(Ordering::SeqCst) < 4 || SCHED_ERR.load(Ordering::SeqCst) < 4)
    {
        tokio::time::sleep(Duration::from_millis(200)).await;
    }
    let elapsed = started.elapsed().as_secs_f64();
    server.abort();
    let k = App::with_config({
        let mut c = config();
        c.database_url = format!("sqlite://{}/s.db", dir.path().display());
        c
    })
    .boot()
    .await
    .unwrap();
    let claims = scalar(
        k.db(),
        "SELECT COUNT(*) FROM cache WHERE key LIKE 'renox:schedule:%'",
    )
    .await;
    let (p, e, s) = (
        SCHED_PANIC.load(Ordering::SeqCst),
        SCHED_ERR.load(Ordering::SeqCst),
        SCHED_SLOW.load(Ordering::SeqCst),
    );
    eprintln!(
        "scheduler: panic-task runs={p}, err-task runs={e}, slow(2.5s)-task runs={s}, claim rows={claims}"
    );
    assert!(e >= 4, "an erroring task keeps its schedule");
    // A 2.5 s task started every second runs at most once per 2.5 s.
    assert!(
        (s as f64) <= elapsed / 2.5 + 1.0,
        "overlapping runs are skipped ({s} runs in {elapsed:.1}s)"
    );
    assert!(
        p >= 4,
        "a task that panicked once never runs again (its `running` flag stays set)"
    );
}

