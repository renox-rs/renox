#[renox::test]
async fn factories_take_states_and_sequences() {
    let (app, _dir) = app().await;
    let db = app.db();
    let made = Bean::factory()
        .count(3)
        .state(sold_out)
        .sequence(|i, bean| bean.name = ["Arabica", "Robusta", "Liberica"][i % 3].into())
        .create(db)
        .await
        .unwrap();
    assert_eq!(made.len(), 3);
    assert!(made.iter().all(|b| b.stock == 0 && b.id != 0));
    assert_eq!(made[1].name, "Robusta");
    assert_eq!(Bean::all(db).await.unwrap().len(), 3);
    let unsaved = Bean::factory()
        .state(|b: &mut Bean| b.stock = 99)
        .make_one();
    assert_eq!((unsaved.id, unsaved.stock), (0, 99));
    let one = Bean::factory().create_one(db).await.unwrap();
    assert_eq!(one.name, "Arabica");
}

