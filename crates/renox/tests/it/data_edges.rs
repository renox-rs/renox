#[renox::test]
async fn where_in_with_a_large_list_of_text() {
    let app = app().await;
    label(&app, "01JA", "first").await;
    label(&app, "01JB", "second").await;
    label(&app, "01JC", "third").await;
    // Over a thousand values go as one JSON array, for text as for numbers.
    let mut codes: Vec<String> = (0..1500).map(|i| format!("X{i:05}")).collect();
    codes.push("01JA".into());
    codes.push("01JC".into());
    let found = Label::query()
        .where_in("code", codes)
        .order_by("code")
        .get(app.db())
        .await
        .unwrap();
    let names: Vec<&str> = found.iter().map(|l| l.name.as_str()).collect();
    assert_eq!(names, ["first", "third"]);
    // A list that isn't all text (here a NULL in it) can't go as one array:
    // plain placeholders, same answer.
    let mut mixed: Vec<renox::db::DbValue> = (0..1200)
        .map(|i| renox::db::DbValue::Text(format!("Y{i}")))
        .collect();
    mixed.push(renox::db::DbValue::Null);
    mixed.push(renox::db::DbValue::Text("01JB".into()));
    let found = Label::query()
        .where_in("code", mixed)
        .get(app.db())
        .await
        .unwrap();
    assert_eq!(found.len(), 1);
}

