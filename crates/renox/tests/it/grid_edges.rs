/// The Excel file read back: numbers with their format, a money column,
/// a date and a moment as dates, text that looks like a number kept as
/// text, an empty cell left out.
#[renox::test]
async fn excel_exports_keep_numbers_dates_and_text_apart() {
    let (app, _lang) = gadgets_app(None).await;
    let res = app.get("/gadgets?export=xlsx").await;
    if !cfg!(feature = "xlsx") {
        return;
    }
    res.assert_ok();
    let mut zip = zip::ZipArchive::new(std::io::Cursor::new(res.body.to_vec())).unwrap();
    let mut read = |name: &str| {
        let mut text = String::new();
        zip.by_name(name)
            .unwrap()
            .read_to_string(&mut text)
            .unwrap();
        text
    };
    let sheet = read("xl/worksheets/sheet1.xml");
    let styles = read("xl/styles.xml");
    let strings = read("xl/sharedStrings.xml");
    assert!(styles.contains(r##"formatCode="#,##0.00""##), "{styles}");
    assert!(styles.contains("yyyy-mm-dd hh:mm") && styles.contains(r#"formatCode="yyyy-mm-dd""#));
    // 1.25 is a number cell; "007" is a shared string, not the number 7.
    assert!(sheet.contains("<v>1.25</v>"), "{sheet}");
    assert!(strings.contains("<t>007</t>"), "{strings}");
    assert!(sheet.contains(r#"<c r="K2" t="s">"#), "{sheet}");
    // The date and the moment (20:00 UTC is 03:00 the next day at +07:00)
    // are dates: 2026-04-01 is day 46113.
    assert!(
        sheet.contains("<v>46113</v>") && sheet.contains("<v>46114.125</v>"),
        "{sheet}"
    );
    // Money in the smallest unit becomes the amount (cents → dollars).
    assert!(sheet.contains("<v>1500</v>"), "{sheet}");
    // Gamma (row 4) has no maker: no cell B4.
    assert!(
        sheet.contains(r#"r="A4""#) && !sheet.contains(r#"r="B4""#),
        "{sheet}"
    );
}

#[renox::test]
async fn a_grid_request_without_renoxs_middleware_is_a_500() {
    use renox::axum::extract::FromRequestParts;

    let (mut parts, ()) = renox::axum::http::Request::new(()).into_parts();
    let Err(res) = GridRequest::from_request_parts(&mut parts, &()).await else {
        panic!("a GridRequest without the middleware");
    };
    assert_eq!(res.status(), 500);
}

/// A sort on a column a `SELECT *` model has without declaring it (an
/// extra column of `users`), both ways.
#[renox::test]
async fn sorting_by_an_extra_column_of_a_select_all_model() {
    async fn users(request: GridRequest) -> Result<renox::axum::Json<Value>> {
        let page = Grid::new("people")
            .column(Column::text("name", "Name"))
            .column(Column::number("score", "Score"))
            .sort_by("-score")
            .page(User::query(), &request)
            .await?;
        Ok(renox::axum::Json(serde_json::to_value(page)?))
    }
    struct People;
    impl Module for People {
        fn name(&self) -> &'static str {
            "people"
        }
        fn routes(&self) -> Routes {
            Routes::new().get("/people", users)
        }
    }
    let app = TestApp::new(App::new().module(Auth::new()).module(People)).await;
    let db = app.db();
    renox::db::sql("ALTER TABLE users ADD COLUMN score BIGINT")
        .execute(db)
        .await
        .unwrap();
    for (name, score) in [("Ann", 2), ("Ben", 9), ("Cy", 5)] {
        let user = User::register(db, name, &format!("{name}@example.com"), "password123")
            .await
            .unwrap();
        renox::db::sql("UPDATE users SET score = ? WHERE id = ?")
            .bind(score)
            .bind(user.id)
            .execute(db)
            .await
            .unwrap();
    }
    let page: Value = app.get("/people").await.json();
    assert_eq!(names(&page), ["Ben", "Cy", "Ann"]);
    let page: Value = app.get("/people?sort=score").await.json();
    assert_eq!(names(&page), ["Ann", "Cy", "Ben"]);
    if app.db().dialect() == Dialect::Postgres {
        // The same order on PostgreSQL, NULLs last either way.
        assert_eq!(page["rows"].as_array().unwrap().len(), 3);
    }
}
