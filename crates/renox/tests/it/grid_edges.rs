//! filter's negative operators on bool, option and text columns with NULL
//! rows, rules and filters the request parser drops, related values for
//! string ids and fractions, groups by a yes/no or a number column, a
//! summary on a column that isn't the model's, a column pinned right, a
//! descending sort on a `SELECT *` model's extra column, `GridRequest`
//! without Renox's middleware, and CSV/Excel exports read back. On SQLite
//! and, with `TEST_DATABASE_URL`, PostgreSQL.

