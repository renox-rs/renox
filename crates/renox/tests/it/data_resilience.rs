#[renox::test]
async fn transaction_error_and_drop_roll_back() {
    let k = kernel().await;
    let db = k.db();
    async fn work(db: &Db) -> Result {
        let mut tx = db.begin().await?;
        Product::create(&mut tx, p("in-tx")).await?;
        Err(Error::BadRequest("boom".into()))?;
        tx.commit().await?;
        Ok(())
    }
    assert!(work(db).await.is_err());
    {
        let mut tx = db.begin().await.unwrap();
        Product::create(&mut tx, p("dropped")).await.unwrap();
    }
    let mut tx = db.begin().await.unwrap();
    Product::create(&mut tx, p("rolled")).await.unwrap();
    tx.rollback().await.unwrap();
    assert_eq!(Product::query().with_trashed().count(db).await.unwrap(), 0);
}

#[renox::test]
async fn nested_begin_on_the_test_pool_fails_fast() {
    // With a transaction open, starting another (or using `&db`) must not
    // deadlock the in-memory/test pool (1 connection on SQLite).
    let k = kernel().await;
    let db = k.db();
    let mut tx = db.begin().await.unwrap();
    Product::create(&mut tx, p("outer")).await.unwrap();
    let started = Instant::now();
    let inner = tokio::time::timeout(Duration::from_secs(5), db.begin()).await;
    eprintln!(
        "nested begin on {:?}: {} after {:?}",
        db.dialect(),
        match &inner {
            Ok(Ok(_)) => "ok".to_owned(),
            Ok(Err(e)) => format!("error {e}"),
            Err(_) => "HUNG (timeout)".to_owned(),
        },
        started.elapsed()
    );
    drop(inner);
    tx.rollback().await.unwrap();
    assert!(
        started.elapsed() < Duration::from_secs(4),
        "nested begin hung"
    );
}

/// SQLite has one writer. A write through `&db` while this task's own
/// transaction holds the lock can't succeed; it must fail within
/// `busy_timeout` with "database is locked", not hang.
#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn file_sqlite_write_while_own_transaction_is_open_fails_fast() {
    let dir = tempfile::tempdir().unwrap();
    let url = format!("sqlite://{}/app.db", dir.path().display());
    let k = kernel_cfg(
        {
            let mut c = config();
            c.database_url = url;
            c
        },
        &[],
    )
    .await;
    let db = k.db();
    let mut tx = db.begin().await.unwrap();
    Product::create(&mut tx, p("outer")).await.unwrap();
    let started = Instant::now();
    let other = Product::create(db, p("other")).await;
    tx.commit().await.unwrap();
    let err = format!("{:?}", other.unwrap_err());
    assert!(err.contains("database is locked"), "{err}");
    // busy_timeout is 5 s; slow CI runners add a few more.
    assert!(
        started.elapsed() < Duration::from_secs(20),
        "it waited, but not forever"
    );
}

