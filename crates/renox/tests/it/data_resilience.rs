#[renox::test]
async fn unique_violation_is_a_conflict() {
    let k = kernel().await;
    let db = k.db();
    renox::db::sql(format!(
        "CREATE TABLE uniq (id {}, code TEXT NOT NULL UNIQUE)",
        pk(db.dialect())
    ))
    .execute(db)
    .await
    .unwrap();
    renox::db::sql("INSERT INTO uniq (code) VALUES (?)")
        .bind("A")
        .execute(db)
        .await
        .unwrap();
    let err = renox::db::sql("INSERT INTO uniq (code) VALUES (?)")
        .bind("A")
        .execute(db)
        .await
        .unwrap_err();
    assert!(err.is_unique_violation(), "DbError reports it: {err}");
    assert!(!err.is_foreign_key_violation());
    let err: Error = err.into();
    eprintln!("unique violation -> {} {:?}", err.status(), err);
    // Robust: a duplicate is a 409/422 the app can show, not a generic 500.
    assert_ne!(err.status(), StatusCode::INTERNAL_SERVER_ERROR);
}

