async fn cache_app(store: &str) -> TestApp {
    let store = match store {
        "database" => renox::CacheStore::Database,
        _ => renox::CacheStore::Memory,
    };
    TestApp::with_config(App::new(), move |c| c.cache_store = store).await
}

#[renox::test]
async fn cache_ttl_zero_is_not_kept() {
    for store in ["memory", "database"] {
        let app = cache_app(store).await;
        let cache = &app.state().cache;
        cache.put("k", &1, Some(Duration::ZERO)).await.unwrap();
        let got: Option<i32> = cache.get("k").await.unwrap();
        eprintln!("{store}: put(ttl=0) then get -> {got:?}");
        cache
            .put("sub", &1, Some(Duration::from_millis(1500)))
            .await
            .unwrap();
        tokio::time::sleep(Duration::from_millis(1100)).await;
        let sub: Option<i32> = cache.get("sub").await.unwrap();
        eprintln!("{store}: ttl=1.5s, read after 1.1s -> {sub:?}");
        assert_eq!(
            got, None,
            "{store}: a zero TTL keeps the value for up to a second"
        );
    }
}

#[renox::test]
async fn cache_huge_values_and_type_mismatch() {
    for store in ["memory", "database"] {
        let app = cache_app(store).await;
        let cache = &app.state().cache;
        let big = "x".repeat(8 * 1024 * 1024);
        cache.put("big", &big, None).await.unwrap();
        let back: Option<String> = cache.get("big").await.unwrap();
        assert_eq!(back.map(|s| s.len()), Some(big.len()));

        cache.put("n", &"not a number", None).await.unwrap();
        assert!(
            cache.get::<i64>("n").await.is_err(),
            "{store}: a wrong type is an error"
        );
        let recomputed = cache
            .remember("n", Duration::from_secs(60), || async { Ok(7i64) })
            .await
            .unwrap();
        assert_eq!(
            recomputed, 7,
            "{store}: remember computes a value of another type again"
        );
    }
}

#[renox::test(flavor = "multi_thread", worker_threads = 4)]
async fn cache_concurrent_remember_computes_once() {
    for store in ["memory", "database"] {
        let app = cache_app(store).await;
        let cache = app.state().cache.clone();
        let calls = Arc::new(AtomicUsize::new(0));
        let mut tasks = Vec::new();
        for _ in 0..20 {
            let (cache, calls) = (cache.clone(), calls.clone());
            tasks.push(tokio::spawn(async move {
                cache
                    .remember("slow", Duration::from_secs(60), || async {
                        calls.fetch_add(1, Ordering::SeqCst);
                        tokio::time::sleep(Duration::from_millis(200)).await;
                        Ok(42i64)
                    })
                    .await
            }));
        }
        for t in tasks {
            assert_eq!(t.await.unwrap().unwrap(), 42);
        }
        let n = calls.load(Ordering::SeqCst);
        eprintln!("{store}: 20 concurrent remember() -> compute ran {n} times");
        assert_eq!(n, 1, "{store}: cache stampede");
    }
}

