#[derive(Model, serde::Serialize, Default, Debug, Clone)]
#[model(table = "products", soft_deletes)]
struct Product {
    id: i64,
    name: String,
    price: i64,
    category: Option<String>,
    created_at: Option<DateTime>,
    updated_at: Option<DateTime>,
    deleted_at: Option<DateTime>,
}

#[derive(Model, serde::Serialize, Default, Debug)]
#[model(table = "notes")]
struct Note {
    id: i64,
    product_id: Option<i64>,
    body: String,
}

fn p(name: &str) -> Product {
    Product {
        name: name.into(),
        price: 1000,
        ..Default::default()
    }
}

pub(crate) fn config() -> Config {
    {
        let mut c = Config::default();
        c.env = Environment::Testing;
        c.key = Some(renox::generate_key());
        c
    }
}

async fn kernel_cfg(config: Config, extra: &[Migration]) -> Kernel {
    let k = App::with_config(config)
        .migrations(renox::migrations!("tests/migrations"))
        .migrations(extra)
        .boot()
        .await
        .unwrap();
    k.migrate().await.unwrap();
    k
}

async fn kernel() -> Kernel {
    kernel_cfg(config(), &[]).await
}

fn pk(d: Dialect) -> &'static str {
    match d {
        Dialect::Sqlite => "INTEGER PRIMARY KEY AUTOINCREMENT",
        Dialect::Postgres => "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    }
}

