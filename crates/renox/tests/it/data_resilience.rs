async fn table_exists(db: &Db, table: &str) -> bool {
    let sql = match db.dialect() {
        Dialect::Sqlite => "SELECT COUNT(*) FROM sqlite_master WHERE name = ?",
        Dialect::Postgres => {
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?"
        }
    };
    renox::db::sql(sql)
        .bind(table)
        .scalar::<i64>(db)
        .await
        .unwrap()
        > 0
}

async fn boot(config: Config, migrations: &[Migration]) -> Kernel {
    App::with_config(config)
        .migrations(migrations)
        .boot()
        .await
        .unwrap()
}

#[renox::test]
async fn failing_migration_mid_batch() {
    let k = boot(config(), &[M_A, M_BAD, M_C]).await;
    let err = k.migrate().await.unwrap_err();
    eprintln!("failing migration: {err:?}");
    let status = k.migration_status().await.unwrap();
    let ran: Vec<_> = status
        .iter()
        .filter(|m| m.name.starts_with("2030"))
        .map(|m| (m.name.clone(), m.batch))
        .collect();
    eprintln!("status after failure: {ran:?}");
    assert!(
        table_exists(k.db(), "m_a").await,
        "earlier migrations are kept"
    );
    assert!(
        !table_exists(k.db(), "m_b1").await,
        "the failed one is rolled back entirely"
    );
    assert!(!table_exists(k.db(), "m_c").await, "later ones don't run");
}

#[renox::test]
async fn rollback_with_a_missing_down_is_all_or_nothing() {
    // Batch = [m_a (no down), m_c (down)]; rollback undoes m_c then fails on m_a.
    let k = boot(config(), &[M_A_NO_DOWN, M_C]).await;
    k.migrate().await.unwrap();
    let err = k.rollback(1).await.unwrap_err();
    eprintln!("rollback without .down.sql: {err:?}");
    let m_c_gone = !table_exists(k.db(), "m_c").await;
    eprintln!("m_c dropped anyway: {m_c_gone}");
    assert!(!m_c_gone, "the batch was half rolled back before the error");

    // And the other order: the newest has no down -> nothing happens.
    let k = boot(config(), &[M_A, M_C_NO_DOWN]).await;
    k.migrate().await.unwrap();
    assert!(k.rollback(1).await.is_err());
    assert!(table_exists(k.db(), "m_a").await && table_exists(k.db(), "m_c").await);
}

#[renox::test]
async fn edited_and_removed_migrations_on_a_file_database() {
    let dir = tempfile::tempdir().unwrap();
    let url = format!("sqlite://{}/app.db", dir.path().display());
    let cfg = || {
        let mut c = config();
        c.database_url = url.clone();
        c
    };
    let k = boot(cfg(), &[M_A, M_C]).await;
    k.migrate().await.unwrap();
    k.db().close().await;
    drop(k);

    // Edited after being applied: silently ignored?
    let k = boot(cfg(), &[M_A_EDITED, M_C]).await;
    let done = k.migrate().await.unwrap();
    let status = k.migration_status().await.unwrap();
    eprintln!(
        "edited migration: migrate ran {done:?}; status says {:?}",
        status
            .iter()
            .find(|m| m.name == M_A.name())
            .map(|m| m.batch)
    );
    k.db().close().await;
    drop(k);

    // Removed but still in renox_migrations.
    let k = boot(cfg(), &[M_A]).await;
    let status = k.migration_status().await.unwrap();
    let listed = status.iter().any(|m| m.name == M_C.name());
    eprintln!("removed migration listed by migrate:status: {listed}");
    let rollback = k.rollback(1).await;
    eprintln!(
        "rollback with a removed migration: {:?}",
        rollback.as_ref().map_err(|e| format!("{e:?}"))
    );
    assert!(
        listed,
        "migrate:status should show applied migrations that are no longer registered"
    );
    assert!(
        rollback.is_ok(),
        "one missing file blocks rolling back its batch forever"
    );
}

