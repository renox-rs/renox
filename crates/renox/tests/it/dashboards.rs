#[derive(Model, serde::Serialize, Default, Debug, Clone)]
#[model(table = "dash_sales")]
struct Sale {
    id: i64,
    status: String,
    total: i64,
    created_at: Option<DateTime>,
}

async fn sale(app: &TestApp, status: &str, total: i64, at: DateTime) {
    Sale::create(
        app.db(),
        Sale {
            status: status.into(),
            total,
            created_at: Some(at),
            ..Default::default()
        },
    )
    .await
    .unwrap();
}

struct Pages;

impl Module for Pages {
    fn name(&self) -> &'static str {
        "dash-pages"
    }

    fn routes(&self) -> Routes {
        Routes::new()
            .get(
                "/trend",
                |State(state): State<AppState>, period: Period| async move {
                    let paid = || Sale::where_eq("status", "paid");
                    let count = Trend::of(paid(), "created_at")
                        .over(period)
                        .count(&state)
                        .await?;
                    let sum = Trend::of(paid(), "created_at")
                        .over(period)
                        .sum(&state, "total")
                        .await?;
                    let before = Trend::of(paid(), "created_at")
                        .over(period.previous())
                        .sum(&state, "total")
                        .await?;
                    let average = Trend::of(paid(), "created_at")
                        .over(period)
                        .average(&state, "total")
                        .await?;
                    Ok::<_, Error>(renox::axum::Json(renox::serde_json::json!({
                        "period": period,
                        "count": count,
                        "sum": sum,
                        "total": sum.total(),
                        "change": sum.change_from(&before),
                        "average": average,
                    })))
                },
            )
            .get("/bad-column", |State(state): State<AppState>| async move {
                Trend::of(Sale::query(), "nope")
                    .count(&state)
                    .await
                    .map(|_| "ok")
            })
            .get("/page", |period: Period| async move {
                let sales = Series::new(
                    vec![
                        "2026-10-01".into(),
                        "2026-10-02".into(),
                        "2026-10-03".into(),
                    ],
                    vec![12_500.0, 30_000.0, 18_000.0],
                )
                .named("Sales");
                view("page.html", context! { period, sales })
            })
            .get("/bad-kind", || async { view("bad.html", context! {}) })
            .get("/bad-points", || async {
                view("bad_points.html", context! {})
            })
    }
}

