#[renox::test]
async fn arabic_search_ignores_marks_and_spelling_variants() {
    let app = parties().await;
    let db = app.db();
    // With or without marks, tatweel or not, whole words or their start.
    for words in ["محمد", "مُحَمَّد", "مـحـمـد", "محم"] {
        assert_eq!(
            names(&Party::search(words).get(db).await.unwrap()),
            ["مُحَمَّد علي"],
            "{words}"
        );
    }
    // Alef forms.
    for words in ["احمد", "أحمد", "إحمد", "ابراهيم", "آبراهيم"] {
        assert_eq!(
            names(&Party::search(words).get(db).await.unwrap()),
            ["أحمد إبراهيم"],
            "{words}"
        );
    }
    // Ta marbuta and ha.
    for words in ["فاطمة", "فاطمه", "الزهراء فاطمه"] {
        assert_eq!(
            names(&Party::search(words).get(db).await.unwrap()),
            ["فاطمة الزهراء"],
            "{words}"
        );
    }
    assert_eq!(Party::search("مدرسه").count(db).await.unwrap(), 1);
    // Ya, alef maqsura and the Persian ya.
    assert_eq!(Party::search("عمیل").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("عميل مهم").count(db).await.unwrap(), 1);
    // Arabic-Indic digits find ASCII digits and the other way round.
    assert_eq!(Party::search("٠٥٥١٢٣٤").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("0123").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("٠١٢٣").count(db).await.unwrap(), 1);
    // Other text still works, and a miss is a miss.
    assert_eq!(
        names(&Party::search("sara").get(db).await.unwrap()),
        ["Sara Smith"]
    );
    assert_eq!(Party::search("english").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("خالد").count(db).await.unwrap(), 0);
    // Combines with other filters, as any search.
    let both = Party::query()
        .where_search("محمد")
        .where_eq("name", "مُحَمَّد علي")
        .count(db)
        .await
        .unwrap();
    assert_eq!(both, 1);
}

