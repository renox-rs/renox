/// The SQL `arabic_sql` builds and `text::normalize_arabic` agree on every
/// rule, on whichever database the tests run.
#[renox::test]
async fn the_normalising_sql_matches_the_rust_function() {
    let app = TestApp::new(App::new()).await;
    let db = app.db();
    let query = format!(
        "SELECT {}",
        search::arabic_sql(db.dialect(), "CAST(? AS TEXT)")
    );
    let mut samples: Vec<String> = Vec::new();
    // Every character a rule names, alone.
    for code in (0x064B..=0x0652).chain([0x0670, 0x0640, 0x0623, 0x0625, 0x0622, 0x0671]) {
        samples.push(char::from_u32(code).unwrap().to_string());
    }
    for c in "ىةکی٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹".chars() {
        samples.push(c.to_string());
    }
    for text in [
        "مُحَمَّدٌ",
        "أحمد إبراهيم آمنة ٱلله",
        "مصطفى فاطمة",
        "کتاب فارسی ۱۲۳",
        "محـــمد",
        "Café 東京 42 O'Brien",
        "",
    ] {
        samples.push(text.to_owned());
    }
    for sample in samples {
        let got: String = renox::db::sql(query.clone())
            .bind(sample.clone())
            .scalar(db)
            .await
            .unwrap();
        assert_eq!(got, renox::text::normalize_arabic(&sample), "{sample:?}");
    }
}

/// A match key column, filled in the `saving` hook, finds a name typed in
/// either script (the recipe of docs/search.md).
#[derive(Model, serde::Serialize, Default, Debug, Clone)]
#[model(table = "contacts", hooks)]
struct Contact {
    id: i64,
    name: String,
    name_key: String,
}

impl renox::db::ModelHooks for Contact {
    fn saving(&mut self, _creating: bool) -> Result {
        self.name_key = renox::text::match_key(&self.name);
        Ok(())
    }
}

const CONTACTS: Migration = Migration::new("20300101000030_contacts", "", Some("DROP TABLE contacts"))
    .sqlite(
        "CREATE TABLE contacts (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, name_key TEXT NOT NULL);
         CREATE INDEX contacts_name_key ON contacts (name_key)",
        None,
    )
    .postgres(
        "CREATE TABLE contacts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, name_key TEXT NOT NULL);
         CREATE INDEX contacts_name_key ON contacts (name_key)",
        None,
    );

#[renox::test]
async fn a_match_key_column_finds_possible_duplicates() {
    let app = TestApp::new(App::new().migrations(&[CONTACTS])).await;
    let db = app.db();
    for name in ["محمد", "Sara Smith"] {
        Contact {
            name: name.into(),
            ..Default::default()
        }
        .save(db)
        .await
        .unwrap();
    }
    let input = "Mohammed";
    let same = Contact::query()
        .where_(Contact::NAME_KEY.eq(renox::text::match_key(input)))
        .get(db)
        .await
        .unwrap();
    assert_eq!(same.len(), 1);
    assert_eq!(same[0].name, "محمد");
}
