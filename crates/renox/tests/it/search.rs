#[renox::test]
async fn arabic_index_follows_updates_deletes_and_rebuilds() {
    let app = parties().await;
    let db = app.db();
    let mut party = Party::search("محمد").first(db).await.unwrap().unwrap();
    party.name = "خَالِد".into();
    party.save(db).await.unwrap();
    assert_eq!(Party::search("محمد").count(db).await.unwrap(), 0);
    assert_eq!(Party::search("خالد").count(db).await.unwrap(), 1);
    // Bulk writes are covered, like any index.
    Party::query()
        .where_eq("name", "خَالِد")
        .update(db, &[("name", &"يُوسُف")])
        .await
        .unwrap();
    assert_eq!(Party::search("يوسف").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("خالد").count(db).await.unwrap(), 0);
    party.delete(db).await.unwrap();
    assert_eq!(Party::search("يوسف").count(db).await.unwrap(), 0);
    // A rebuild indexes the normalised text, not the text as written.
    search::rebuild::<Party>(db).await.unwrap();
    assert_eq!(Party::search("احمد ابراهيم").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("فاطمه").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("sara").count(db).await.unwrap(), 1);
    assert_eq!(Party::search("يوسف").count(db).await.unwrap(), 0);
}

