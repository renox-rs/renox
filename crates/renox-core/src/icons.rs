/// The elements of the icon `name` (a Lucide name, or one of the kit's
/// older names), or `None` for a name the set doesn't have.
pub(crate) fn paths(name: &str) -> Option<&'static str> {
    let name = ALIASES
        .iter()
        .find(|(alias, _)| *alias == name)
        .map_or(name, |(_, real)| real);
    ICONS
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| ICONS[i].1)
}

/// The `<svg>` of the icon `name`, `size` pixels square, in `currentColor`.
/// Decorative (`aria-hidden`) unless it has a `label`, which makes it an
/// image with that name (`role="img"`). `class` is added after `rx-icon`.
/// An unknown name gives an empty string.
pub(crate) fn svg(name: &str, size: u32, label: Option<&str>, class: Option<&str>) -> String {
    let Some(paths) = paths(name) else {
        return String::new();
    };
    let mut out = String::from("<svg class=\"rx-icon");
    if let Some(class) = class.filter(|c| !c.is_empty()) {
        out.push(' ');
        out.push_str(&escape(class));
    }
    let _ = write!(
        out,
        "\" xmlns=\"http://www.w3.org/2000/svg\" width=\"{size}\" height=\"{size}\" \
         viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"{STROKE}\" \
         stroke-linecap=\"round\" stroke-linejoin=\"round\" focusable=\"false\""
    );
    match label.filter(|l| !l.is_empty()) {
        Some(label) => {
            let _ = write!(out, " role=\"img\" aria-label=\"{}\"", escape(label));
        }
        None => out.push_str(" aria-hidden=\"true\""),
    }
    out.push('>');
    out.push_str(paths);
    out.push_str("</svg>");
    out
}

/// `& < > " '` escaped for an attribute.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_icons_are_sorted_and_every_alias_names_one() {
        assert!(
            ICONS.windows(2).all(|w| w[0].0 < w[1].0),
            "ICONS must stay sorted"
        );
        for (alias, real) in ALIASES {
            assert!(paths(real).is_some(), "{alias} → {real}");
            assert!(paths(alias).is_some(), "{alias}");
        }
    }

    #[test]
    fn an_icon_is_hidden_unless_labelled() {
        let plain = svg("bike", 20, None, None);
        assert!(plain.starts_with("<svg class=\"rx-icon\""), "{plain}");
        assert!(plain.contains("width=\"20\" height=\"20\""));
        assert!(plain.contains("stroke-width=\"1.75\""));
        assert!(plain.contains("aria-hidden=\"true\""));
        assert!(!plain.contains("role="));
        let named = svg("cart", 16, Some("Cart \"3\""), Some("big"));
        assert_eq!(named, "", "no such icon");
        let named = svg("shopping-cart", 16, Some("Cart \"3\""), Some("big"));
        assert!(named.starts_with("<svg class=\"rx-icon big\""), "{named}");
        assert!(named.contains("role=\"img\" aria-label=\"Cart &quot;3&quot;\""));
        assert!(!named.contains("aria-hidden"));
        assert_eq!(svg("trash", 16, None, None), svg("trash-2", 16, None, None));
    }
}
