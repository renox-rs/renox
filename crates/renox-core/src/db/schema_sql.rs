    fn cx_for(table: &str, create: &str, cols: Vec<TableColumn>) -> SqliteContext {
        let mut cx = SqliteContext::default();
        cx.tables.insert(
            table.into(),
            TableState {
                table: table.into(),
                columns: cols,
                indexes: vec![TableIndex {
                    name: "t_a_index".into(),
                    columns: vec!["a".into()],
                    unique: false,
                    sql: Some("CREATE INDEX t_a_index ON t (a)".into()),
                }],
            },
        );
        cx.table_sql.insert(table.into(), create.into());
        cx
    }

    const CREATE: &str =
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, a INTEGER NOT NULL, b TEXT)";

    fn t_cols() -> Vec<TableColumn> {
        let mut id = old("id", "INTEGER", false);
        id.primary_key = true;
        vec![id, old("a", "INTEGER", true), old("b", "TEXT", false)]
    }

    #[test]
    fn sqlite_adds_stay_alter_table() {
        let changes = [
            Change::AddColumn {
                table: "t".into(),
                column: col("c", ColumnKind::Text, true),
            },
            Change::AddColumn {
                table: "t".into(),
                column: col("d", ColumnKind::Bool, false).default_sql("0"),
            },
            Change::RenameColumn {
                table: "t".into(),
                from: "b".into(),
                to: "e".into(),
            },
        ];
        let (up, down) = sqlite(&changes, &SqliteContext::default()).unwrap();
        assert!(up.contains("ALTER TABLE \"t\" ADD COLUMN \"c\" TEXT;"));
        assert!(up.contains("ADD COLUMN \"d\" INTEGER NOT NULL DEFAULT 0;"));
        assert!(!up.contains("__new_"));
        assert!(down.starts_with("ALTER TABLE \"t\" RENAME COLUMN \"e\" TO \"b\";"));
        assert!(down.contains("DROP COLUMN \"c\""));
    }

    #[test]
    fn sqlite_type_change_is_a_rebuild() {
        let cx = cx_for("t", CREATE, t_cols());
        let changes = [Change::AlterColumn {
            table: "t".into(),
            old: old("b", "TEXT", false),
            new: col("b", ColumnKind::Int, false),
        }];
        let (up, down) = sqlite(&changes, &cx).unwrap();
        assert!(up.starts_with("PRAGMA defer_foreign_keys = ON;\nCREATE TABLE \"__new_t\""));
        assert!(up.contains("\"b\" INTEGER NOT NULL"));
        assert!(up.contains(
            "INSERT INTO \"__new_t\" (\"id\", \"a\", \"b\") SELECT \"id\", \"a\", \"b\" FROM \"t\";"
        ));
        assert!(up.contains("DROP TABLE \"t\";\nCREATE TABLE \"t\" ("));
        assert!(up.contains("DROP TABLE \"__new_t\";"));
        assert!(up.contains("CREATE INDEX t_a_index ON t (a);"));
        assert!(up.contains("AUTOINCREMENT"));
        assert!(down.contains("b TEXT"));
    }

    #[test]
    fn sqlite_rebuild_guards() {
        let change = [Change::DropColumn {
            table: "t".into(),
            old: old("b", "TEXT", false),
        }];
        for create in [
            "CREATE TABLE t (id INTEGER PRIMARY KEY, a INTEGER CHECK (a > 0), b TEXT)",
            "CREATE TABLE t (id INTEGER PRIMARY KEY, a INTEGER, b TEXT, CONSTRAINT x UNIQUE (a))",
            "CREATE TABLE t (id INTEGER, a INTEGER, b TEXT, UNIQUE (a))",
            "CREATE TABLE t (id INTEGER, a INTEGER, b TEXT, PRIMARY KEY (id))",
        ] {
            let cx = cx_for("t", create, t_cols());
            let err = sqlite(&change, &cx).unwrap_err().to_string();
            assert!(
                err.contains("write this migration by hand"),
                "{create}: {err}"
            );
        }
        let mut cx = cx_for("t", CREATE, t_cols());
        for (action, fails) in [
            ("CASCADE", true),
            ("SET NULL", true),
            ("NO ACTION", false),
            ("RESTRICT", false),
        ] {
            cx.referenced_by.insert(
                "t".into(),
                vec![ForeignKey {
                    table: "child".into(),
                    column: "t_id".into(),
                    references: "t".into(),
                    on_delete: action.into(),
                }],
            );
            assert_eq!(sqlite(&change, &cx).is_err(), fails, "{action}");
        }
        // A column called "checked" is not a CHECK constraint.
        let cx = cx_for(
            "t",
            "CREATE TABLE t (id INTEGER PRIMARY KEY, a INTEGER, checked INTEGER, b TEXT)",
            t_cols(),
        );
        assert!(sqlite(&change, &cx).is_ok());
    }

