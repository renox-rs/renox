/// The SQL type of a column kind; `None` for [`ColumnKind::Unknown`].
pub(crate) fn sql_type(kind: ColumnKind, dialect: Dialect) -> Option<&'static str> {
    use ColumnKind as K;
    let pg = dialect == Dialect::Postgres;
    let (lite, postgres) = match kind {
        K::BigInt => ("INTEGER", "BIGINT"),
        K::Int => ("INTEGER", "INTEGER"),
        K::SmallInt => ("INTEGER", "SMALLINT"),
        K::Double => ("REAL", "DOUBLE PRECISION"),
        K::Real => ("REAL", "REAL"),
        K::Text => ("TEXT", "TEXT"),
        K::Blob => ("BLOB", "BYTEA"),
        K::Bool => ("INTEGER", "BOOLEAN"),
        K::DateTime => ("TEXT", "TIMESTAMPTZ"),
        K::NaiveDateTime => ("TEXT", "TIMESTAMP"),
        K::Date => ("TEXT", "DATE"),
        K::Time => ("TEXT", "TIME"),
        K::Json => ("TEXT", "JSONB"),
        K::Uuid => ("BLOB", "UUID"),
        K::Unknown => return None,
    };
    Some(if pg { postgres } else { lite })
}

/// `"name" TYPE [NOT NULL] [DEFAULT x] [REFERENCES "t" ("id")]`; the `id`
/// column is the primary key.
pub(crate) fn column_def(c: &ModelColumn, dialect: Dialect) -> String {
    let name = quote(c.name);
    let ty = sql_type(c.kind, dialect).unwrap_or("TEXT");
    if c.name == "id" {
        return match (c.kind, dialect) {
            (ColumnKind::BigInt | ColumnKind::Int, Dialect::Sqlite) => {
                format!("{name} INTEGER PRIMARY KEY AUTOINCREMENT")
            }
            (ColumnKind::BigInt | ColumnKind::Int, Dialect::Postgres) => {
                format!("{name} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            }
            _ => format!("{name} {ty} PRIMARY KEY"),
        };
    }
    let mut out = format!("{name} {ty}");
    if !c.nullable {
        out.push_str(" NOT NULL");
    }
    if let Some(default) = c.default {
        out.push_str(&format!(" DEFAULT {default}"));
    }
    if let Some(table) = c.references {
        out.push_str(&format!(" REFERENCES {} (\"id\")", quote(table)));
    }
    out
}

fn columns_list(columns: &[String]) -> String {
    columns
        .iter()
        .map(|c| quote(c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The PostgreSQL `(up, down)` SQL for `changes`: up in order, down in
/// reverse order, every statement ending in `;\n`.
pub(crate) fn postgres(changes: &[Change]) -> (String, String) {
    let d = Dialect::Postgres;
    let mut up = String::new();
    let mut downs: Vec<String> = Vec::new();
    for change in changes {
        let mut down = String::new();
        match change {
            Change::CreateTable { model } => {
                let defs: Vec<String> = model.columns.iter().map(|c| column_def(c, d)).collect();
                up.push_str(&format!(
                    "CREATE TABLE {} (\n    {}\n);\n",
                    quote(model.table),
                    defs.join(",\n    ")
                ));
                down.push_str(&format!("DROP TABLE {};\n", quote(model.table)));
            }
            Change::AddColumn { table, column } => {
                up.push_str(&format!(
                    "ALTER TABLE {} ADD COLUMN {};\n",
                    quote(table),
                    column_def(column, d)
                ));
                down.push_str(&format!(
                    "ALTER TABLE {} DROP COLUMN {};\n",
                    quote(table),
                    quote(column.name)
                ));
            }
            Change::DropColumn { table, old } => {
                up.push_str(&format!(
                    "ALTER TABLE {} DROP COLUMN {};\n",
                    quote(table),
                    quote(&old.name)
                ));
                let mut def = format!("{} {}", quote(&old.name), old.sql_type);
                if old.not_null {
                    def.push_str(" NOT NULL");
                }
                if let Some(default) = &old.default {
                    def.push_str(&format!(" DEFAULT {default}"));
                }
                down.push_str(&format!("ALTER TABLE {} ADD COLUMN {def};\n", quote(table)));
            }
            Change::AlterColumn { table, old, new } => {
                let t = quote(table);
                let c = quote(new.name);
                let new_ty = sql_type(new.kind, d).unwrap_or("TEXT");
                if !kind_fits(d, new.kind, &old.sql_type) {
                    up.push_str(&format!(
                        "ALTER TABLE {t} ALTER COLUMN {c} TYPE {new_ty} USING {c}::{new_ty};\n"
                    ));
                    down.push_str(&format!(
                        "ALTER TABLE {t} ALTER COLUMN {c} TYPE {0} USING {c}::{0};\n",
                        old.sql_type
                    ));
                }
                if new.nullable == old.not_null {
                    let (to, back) = if new.nullable {
                        ("DROP", "SET")
                    } else {
                        ("SET", "DROP")
                    };
                    up.push_str(&format!(
                        "ALTER TABLE {t} ALTER COLUMN {c} {to} NOT NULL;\n"
                    ));
                    down.insert_str(
                        0,
                        &format!("ALTER TABLE {t} ALTER COLUMN {c} {back} NOT NULL;\n"),
                    );
                }
            }
            Change::RenameColumn { table, from, to } => {
                up.push_str(&format!(
                    "ALTER TABLE {} RENAME COLUMN {} TO {};\n",
                    quote(table),
                    quote(from),
                    quote(to)
                ));
                down.push_str(&format!(
                    "ALTER TABLE {} RENAME COLUMN {} TO {};\n",
                    quote(table),
                    quote(to),
                    quote(from)
                ));
            }
            Change::CreateIndex {
                table,
                name,
                columns,
                unique,
            } => {
                up.push_str(&format!(
                    "CREATE {}INDEX {} ON {} ({});\n",
                    if *unique { "UNIQUE " } else { "" },
                    quote(name),
                    quote(table),
                    columns_list(columns)
                ));
                down.push_str(&format!("DROP INDEX {};\n", quote(name)));
            }
            Change::DropIndex { old, .. } => {
                up.push_str(&format!("DROP INDEX {};\n", quote(&old.name)));
                if let Some(sql) = &old.sql {
                    down.push_str(sql.trim_end_matches(';'));
                    down.push_str(";\n");
                }
            }
        }
        downs.push(down);
    }
    downs.reverse();
    (up, downs.concat())
}

/// What the SQLite writer needs to know about the current database; the
/// caller fills it with the readers of `schema_check`.
#[derive(Debug, Clone, Default)]
pub(crate) struct SqliteContext {
    /// The tables as they are now.
    pub tables: HashMap<String, TableState>,
    /// Each table's own `CREATE TABLE` text.
    pub table_sql: HashMap<String, String>,
    /// The foreign keys of other tables that point at each table.
    pub referenced_by: HashMap<String, Vec<ForeignKey>>,
}

fn change_table(change: &Change) -> &str {
    match change {
        Change::CreateTable { model } => model.table,
        Change::AddColumn { table, .. }
        | Change::DropColumn { table, .. }
        | Change::AlterColumn { table, .. }
        | Change::RenameColumn { table, .. }
        | Change::CreateIndex { table, .. }
        | Change::DropIndex { table, .. } => table,
    }
}

/// Whether SQLite can do the group's changes with `ALTER TABLE` alone.
fn is_simple(group: &[&Change]) -> bool {
    group
        .iter()
        .any(|c| matches!(c, Change::CreateTable { .. }))
        || group.iter().all(|c| match c {
            Change::AddColumn { column, .. } => {
                column.nullable || (column.default.is_some() && column.references.is_none())
            }
            Change::RenameColumn { .. } | Change::CreateIndex { .. } | Change::DropIndex { .. } => {
                true
            }
            _ => false,
        })
}

fn create_index_sql(table: &str, name: &str, columns: &[String], unique: bool) -> String {
    format!(
        "CREATE {}INDEX {} ON {} ({});\n",
        if unique { "UNIQUE " } else { "" },
        quote(name),
        quote(table),
        columns_list(columns)
    )
}

fn with_semicolon(sql: &str) -> String {
    format!("{};\n", sql.trim().trim_end_matches(';'))
}

/// The SQL for a group of changes that need only `ALTER TABLE` and indexes.
fn simple(group: &[&Change]) -> (String, String) {
    let d = Dialect::Sqlite;
    let mut up = String::new();
    let mut downs: Vec<String> = Vec::new();
    for change in group {
        let mut down = String::new();
        match change {
            Change::CreateTable { model } => {
                let defs: Vec<String> = model.columns.iter().map(|c| column_def(c, d)).collect();
                up.push_str(&format!(
                    "CREATE TABLE {} (\n    {}\n);\n",
                    quote(model.table),
                    defs.join(",\n    ")
                ));
                down.push_str(&format!("DROP TABLE {};\n", quote(model.table)));
            }
            Change::AddColumn { table, column } => {
                up.push_str(&format!(
                    "ALTER TABLE {} ADD COLUMN {};\n",
                    quote(table),
                    column_def(column, d)
                ));
                down.push_str(&format!(
                    "ALTER TABLE {} DROP COLUMN {};\n",
                    quote(table),
                    quote(column.name)
                ));
            }
            Change::RenameColumn { table, from, to } => {
                up.push_str(&format!(
                    "ALTER TABLE {} RENAME COLUMN {} TO {};\n",
                    quote(table),
                    quote(from),
                    quote(to)
                ));
                down.push_str(&format!(
                    "ALTER TABLE {} RENAME COLUMN {} TO {};\n",
                    quote(table),
                    quote(to),
                    quote(from)
                ));
            }
            Change::CreateIndex {
                table,
                name,
                columns,
                unique,
            } => {
                up.push_str(&create_index_sql(table, name, columns, *unique));
                down.push_str(&format!("DROP INDEX {};\n", quote(name)));
            }
            Change::DropIndex { old, .. } => {
                up.push_str(&format!("DROP INDEX {};\n", quote(&old.name)));
                if let Some(sql) = &old.sql {
                    down.push_str(&with_semicolon(sql));
                }
            }
            Change::DropColumn { .. } | Change::AlterColumn { .. } => {}
        }
        downs.push(down);
    }
    downs.reverse();
    (up, downs.concat())
}

/// Whether `word` appears in `sql` as a keyword (not inside a longer name);
/// with `paren`, only when an opening parenthesis follows it.
fn has_keyword(sql: &str, word: &str, paren: bool) -> bool {
    let lower = sql.to_lowercase();
    let bytes = lower.as_bytes();
    let ident = |b: u8| b.is_ascii_alphanumeric() || b == b'_';
    let mut from = 0;
    while let Some(at) = lower[from..].find(word) {
        let start = from + at;
        let end = start + word.len();
        from = start + 1;
        if start > 0 && ident(bytes[start - 1]) {
            continue;
        }
        if end < bytes.len() && ident(bytes[end]) {
            continue;
        }
        if paren && !lower[end..].trim_start().starts_with('(') {
            continue;
        }
        return true;
    }
    false
}

/// The first reason the table can't be rebuilt safely, if any.
fn rebuild_problem(table: &str, cx: &SqliteContext) -> Option<String> {
    let Some(sql) = cx.table_sql.get(table) else {
        return Some("its CREATE TABLE text is unknown".into());
    };
    if has_keyword(sql, "check", false) {
        return Some("it has a CHECK constraint".into());
    }
    if has_keyword(sql, "constraint", false) {
        return Some("it has a named constraint".into());
    }
    if has_keyword(sql, "unique", true) {
        return Some("it has a table-level UNIQUE".into());
    }
    if has_keyword(sql, "primary key", true) {
        return Some("it has a table-level PRIMARY KEY".into());
    }
    if let Some(key) = cx.referenced_by.get(table).and_then(|keys| {
        keys.iter().find(|k| {
            let a = k.on_delete.to_uppercase();
            a != "NO ACTION" && a != "RESTRICT"
        })
    }) {
        return Some(format!(
            "`{}.{}` references it with ON DELETE {}",
            key.table, key.column, key.on_delete
        ));
    }
    None
}

fn needs_hand(table: &str, why: &str) -> crate::Error {
    crate::Error::Internal(anyhow::anyhow!(
        "`{table}` needs a table rebuild that Renox can't write safely ({why}); \
         write this migration by hand"
    ))
}

/// The pieces of a `CREATE TABLE`: its column definitions (by lowercase name)
/// and the other clauses, in order.
struct Body {
    columns: Vec<(String, String)>,
    others: Vec<String>,
}

fn split_body(sql: &str) -> Option<Body> {
    let open = sql.find('(')?;
    let close = sql.rfind(')')?;
    if close <= open {
        return None;
    }
    let body = &sql[open + 1..close];
    let mut parts: Vec<String> = Vec::new();
    let (mut depth, mut quote_ch, mut cur) = (0usize, None::<char>, String::new());
    for c in body.chars() {
        match quote_ch {
            Some(q) => {
                if c == q || (q == '[' && c == ']') {
                    quote_ch = None;
                }
                cur.push(c);
            }
            None => match c {
                '\'' | '"' | '`' | '[' => {
                    quote_ch = Some(c);
                    cur.push(c);
                }
                '(' => {
                    depth += 1;
                    cur.push(c);
                }
                ')' => {
                    depth = depth.saturating_sub(1);
                    cur.push(c);
                }
                ',' if depth == 0 => parts.push(std::mem::take(&mut cur)),
                _ => cur.push(c),
            },
        }
    }
    parts.push(cur);
    let mut out = Body {
        columns: Vec::new(),
        others: Vec::new(),
    };
    for part in parts {
        let part = part.trim().to_string();
        if part.is_empty() {
            continue;
        }
        let (name, rest) = leading_identifier(&part);
        let lower = name.to_lowercase();
        if matches!(
            lower.as_str(),
            "constraint" | "primary" | "unique" | "check" | "foreign"
        ) && !part.starts_with(['"', '`', '['])
        {
            out.others.push(part);
        } else {
            let _ = rest;
            out.columns.push((lower, part));
        }
    }
    Some(out)
}

/// The identifier a definition starts with, and the text after it.
fn leading_identifier(def: &str) -> (String, &str) {
    let mut chars = def.char_indices();
    match chars.next() {
        Some((_, q @ ('"' | '`' | '['))) => {
            let end = if q == '[' { ']' } else { q };
            match def[1..].find(end) {
                Some(i) => (def[1..1 + i].to_string(), &def[i + 2..]),
                None => (def.to_string(), ""),
            }
        }
        _ => match def.find(char::is_whitespace) {
            Some(i) => (def[..i].to_string(), &def[i..]),
            None => (def.to_string(), ""),
        },
    }
}

/// A definition from the table's own SQL, under a new name when asked.
fn kept_def(body: Option<&Body>, col: &TableColumn, new_name: &str) -> String {
    if let Some(body) = body
        && let Some((_, def)) = body
            .columns
            .iter()
            .find(|(n, _)| *n == col.name.to_lowercase())
    {
        let (_, rest) = leading_identifier(def);
        return format!("{}{}", quote(new_name), rest);
    }
    let mut out = format!("{} {}", quote(new_name), col.sql_type);
    if col.primary_key {
        out.push_str(" PRIMARY KEY");
    } else {
        if col.not_null {
            out.push_str(" NOT NULL");
        }
        if let Some(default) = &col.default {
            out.push_str(&format!(" DEFAULT {default}"));
        }
    }
    out
}

/// The statements that replace `table` with one of the given shape, copying
/// `into` from `from` (a select list over the old table).
///
/// The rows go through a staging table `__new_t`, and the table is created
/// again under its own name rather than renamed: after `DROP TABLE`, SQLite
/// only forgets the foreign keys of other tables that pointed at it when rows
/// are inserted into a table of that name (renaming leaves `COMMIT` failing).
fn rebuild_statements(table: &str, defs: &[String], into: &[String], from: &str) -> String {
    let temp = quote(&format!("__new_{table}"));
    let t = quote(table);
    let body = defs.join(",\n    ");
    let mut out = String::from("PRAGMA defer_foreign_keys = ON;\n");
    out.push_str(&format!("CREATE TABLE {temp} (\n    {body}\n);\n"));
    if !into.is_empty() {
        out.push_str(&format!(
            "INSERT INTO {temp} ({}) SELECT {from} FROM {t};\n",
            columns_list(into)
        ));
    }
    out.push_str(&format!("DROP TABLE {t};\n"));
    out.push_str(&format!("CREATE TABLE {t} (\n    {body}\n);\n"));
    if !into.is_empty() {
        let list = columns_list(into);
        out.push_str(&format!(
            "INSERT INTO {t} ({list}) SELECT {list} FROM {temp};\n"
        ));
    }
    out.push_str(&format!("DROP TABLE {temp};\n"));
    out
}

/// Rebuilds `table` (decision 9): `(up, down)`.
fn rebuild(table: &str, group: &[&Change], cx: &SqliteContext) -> crate::Result<(String, String)> {
    if let Some(why) = rebuild_problem(table, cx) {
        return Err(needs_hand(table, &why));
    }
    let state = cx.tables.get(table).ok_or_else(|| {
        crate::Error::Internal(anyhow::anyhow!(
            "the table `{table}` is not in the schema read"
        ))
    })?;
    let body = cx.table_sql.get(table).and_then(|s| split_body(s));
    let mut renames: HashMap<&str, &str> = HashMap::new();
    let mut dropped: Vec<&str> = Vec::new();
    let mut altered: HashMap<&str, &ModelColumn> = HashMap::new();
    let mut added: Vec<&ModelColumn> = Vec::new();
    for change in group {
        match change {
            Change::RenameColumn { from, to, .. } => {
                renames.insert(from, to);
            }
            Change::DropColumn { old, .. } => dropped.push(&old.name),
            Change::AlterColumn { old, new, .. } => {
                altered.insert(&old.name, new);
            }
            Change::AddColumn { column, .. } => added.push(column),
            _ => {}
        }
    }
    let mut new_defs: Vec<String> = Vec::new();
    let mut shared: Vec<(&str, String)> = Vec::new(); // (old name, new name)
    let mut coalesce: HashMap<&str, &str> = HashMap::new();
    for col in &state.columns {
        if dropped.contains(&col.name.as_str()) {
            continue;
        }
        let new_name = renames
            .get(col.name.as_str())
            .map_or(col.name.clone(), |n| n.to_string());
        match altered.get(col.name.as_str()) {
            Some(new) => {
                new_defs.push(column_def(new, Dialect::Sqlite));
                // NULLs become the default when the column turns NOT NULL.
                if let (false, false, Some(default)) = (new.nullable, col.not_null, new.default) {
                    coalesce.insert(&col.name, default);
                }
            }
            None => new_defs.push(kept_def(body.as_ref(), col, &new_name)),
        }
        shared.push((&col.name, new_name));
    }
    for column in &added {
        new_defs.push(column_def(column, Dialect::Sqlite));
    }
    let touched = |name: &str| dropped.contains(&name) || renames.contains_key(name);
    for other in body.iter().flat_map(|b| &b.others) {
        for col in &state.columns {
            if touched(&col.name) && has_keyword(other, &col.name.to_lowercase(), false) {
                return Err(needs_hand(
                    table,
                    "a table-level clause names a changed column",
                ));
            }
        }
        new_defs.push(other.clone());
    }
    let into: Vec<String> = shared.iter().map(|(_, n)| n.clone()).collect();
    let from: Vec<String> = shared
        .iter()
        .map(|(o, _)| match coalesce.get(o) {
            Some(default) => format!("COALESCE({}, {default})", quote(o)),
            None => quote(o),
        })
        .collect();
    let mut up = rebuild_statements(table, &new_defs, &into, &from.join(", "));
    // Indexes: the old ones that survive, then the new ones.
    let dropped_indexes: Vec<&str> = group
        .iter()
        .filter_map(|c| match c {
            Change::DropIndex { old, .. } => Some(old.name.as_str()),
            _ => None,
        })
        .collect();
    for index in &state.indexes {
        let Some(sql) = &index.sql else { continue };
        if dropped_indexes.contains(&index.name.as_str())
            || index.columns.iter().any(|c| dropped.contains(&c.as_str()))
        {
            continue;
        }
        if index
            .columns
            .iter()
            .any(|c| renames.contains_key(c.as_str()))
        {
            if has_keyword(sql, "where", false) {
                return Err(needs_hand(table, "a partial index uses a renamed column"));
            }
            let columns: Vec<String> = index
                .columns
                .iter()
                .map(|c| renames.get(c.as_str()).map_or(c.clone(), |n| n.to_string()))
                .collect();
            up.push_str(&create_index_sql(
                table,
                &index.name,
                &columns,
                index.unique,
            ));
        } else {
            up.push_str(&with_semicolon(sql));
        }
    }
    for change in group {
        if let Change::CreateIndex {
            name,
            columns,
            unique,
            ..
        } = change
        {
            up.push_str(&create_index_sql(table, name, columns, *unique));
        }
    }
    // Down: the old table again.
    let old_defs: Vec<String> = match &body {
        Some(b) => b
            .columns
            .iter()
            .map(|(_, d)| d.clone())
            .chain(b.others.iter().cloned())
            .collect(),
        None => state
            .columns
            .iter()
            .map(|c| kept_def(None, c, &c.name))
            .collect(),
    };
    let back_into: Vec<String> = shared.iter().map(|(o, _)| o.to_string()).collect();
    let back_from = columns_list(&into);
    let mut down = rebuild_statements(table, &old_defs, &back_into, &back_from);
    for index in &state.indexes {
        if let Some(sql) = &index.sql {
            down.push_str(&with_semicolon(sql));
        }
    }
    Ok((up, down))
}

/// The SQLite `(up, down)` SQL for `changes`: up in order, down in reverse
/// order. A table that `ALTER TABLE` can't change is rebuilt (decision 9).
pub(crate) fn sqlite(changes: &[Change], cx: &SqliteContext) -> crate::Result<(String, String)> {
    let mut groups: Vec<(String, Vec<&Change>)> = Vec::new();
    for change in changes {
        let table = change_table(change);
        match groups.iter_mut().find(|(t, _)| t == table) {
            Some((_, g)) => g.push(change),
            None => groups.push((table.to_string(), vec![change])),
        }
    }
    let mut up = String::new();
    let mut downs: Vec<String> = Vec::new();
    for (table, group) in &groups {
        let (u, d) = if is_simple(group) {
            simple(group)
        } else {
            rebuild(table, group, cx)?
        };
        up.push_str(&u);
        downs.push(d);
    }
    downs.reverse();
    Ok((up, downs.concat()))
}

