    /// Up then down returns to the starting columns (PostgreSQL only).
    #[tokio::test]
    async fn up_then_down_restores_the_columns_on_postgres() {
        use crate::db::schema_check::table_columns;
        let db = crate::db::connect(&crate::Config::default()).await.unwrap();
        if db.dialect() != Dialect::Postgres {
            return;
        }
        crate::db::script(
            &db,
            "CREATE TABLE rt_posts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
             a INTEGER NOT NULL, b TEXT, c TEXT NOT NULL DEFAULT 'x', d TEXT);",
        )
        .await
        .unwrap();
        let before = table_columns(&db, "rt_posts").await.unwrap();
        let changes = [
            Change::AddColumn {
                table: "rt_posts".into(),
                column: col("e", ColumnKind::Bool, false).default_sql("false"),
            },
            Change::DropColumn {
                table: "rt_posts".into(),
                old: before.iter().find(|c| c.name == "c").unwrap().clone(),
            },
            Change::AlterColumn {
                table: "rt_posts".into(),
                old: before.iter().find(|c| c.name == "a").unwrap().clone(),
                new: col("a", ColumnKind::Text, true),
            },
            Change::AlterColumn {
                table: "rt_posts".into(),
                old: before.iter().find(|c| c.name == "b").unwrap().clone(),
                new: col("b", ColumnKind::Text, false),
            },
            Change::RenameColumn {
                table: "rt_posts".into(),
                from: "d".into(),
                to: "f".into(),
            },
            Change::CreateIndex {
                table: "rt_posts".into(),
                name: "rt_posts_a_index".into(),
                columns: vec!["a".into()],
                unique: false,
            },
        ];
        let (up, down) = postgres(&changes);
        for text in [&up, &down] {
            for stmt in text.split(";\n").filter(|s| !s.trim().is_empty()) {
                crate::db::sql(stmt).execute(&db).await.unwrap();
            }
            if text == &up {
                let mid = table_columns(&db, "rt_posts").await.unwrap();
                assert_ne!(mid.len(), 0);
                assert!(mid.iter().any(|c| c.name == "f" && c.name != "d"));
            }
        }
        let after = table_columns(&db, "rt_posts").await.unwrap();
        let key = |v: &[crate::db::schema_check::TableColumn]| {
            v.iter()
                .map(|c| (c.name.clone(), c.sql_type.to_lowercase(), c.not_null))
                .collect::<Vec<_>>()
        };
        let mut b = key(&before);
        let mut a = key(&after);
        b.sort();
        a.sort();
        assert_eq!(b, a);
    }

    /// A rebuild keeps rows and indexes, and the down restores the columns
    /// (SQLite only).
    #[tokio::test]
    async fn rebuild_keeps_rows_and_indexes_on_sqlite() {
        use crate::db::schema_check::{
            foreign_keys_to, sqlite_table_sql, table_columns, table_indexes,
        };
        let db = crate::db::connect(&crate::Config::default()).await.unwrap();
        if db.dialect() != Dialect::Sqlite {
            return;
        }
        crate::db::script(
            &db,
            "CREATE TABLE rb_posts (id INTEGER PRIMARY KEY AUTOINCREMENT, a TEXT NOT NULL, \
             b TEXT, c TEXT NOT NULL DEFAULT 'x');\n\
             CREATE INDEX rb_posts_a_index ON rb_posts (a);\n\
             CREATE TABLE rb_comments (id INTEGER PRIMARY KEY, post_id INTEGER NOT NULL \
             REFERENCES rb_posts (id));\n\
             INSERT INTO rb_posts (a, b) VALUES ('1', 'x'), ('2', NULL);\n\
             INSERT INTO rb_comments (post_id) VALUES (1), (2);",
        )
        .await
        .unwrap();
        let before = table_columns(&db, "rb_posts").await.unwrap();
        let mut cx = SqliteContext::default();
        cx.tables.insert(
            "rb_posts".into(),
            TableState {
                table: "rb_posts".into(),
                columns: before.clone(),
                indexes: table_indexes(&db, "rb_posts").await.unwrap(),
            },
        );
        cx.table_sql.insert(
            "rb_posts".into(),
            sqlite_table_sql(&db, "rb_posts").await.unwrap().unwrap(),
        );
        cx.referenced_by.insert(
            "rb_posts".into(),
            foreign_keys_to(&db, "rb_posts").await.unwrap(),
        );
        let changes = [
            Change::AlterColumn {
                table: "rb_posts".into(),
                old: before.iter().find(|c| c.name == "a").unwrap().clone(),
                new: col("a", ColumnKind::BigInt, false),
            },
            Change::AlterColumn {
                table: "rb_posts".into(),
                old: before.iter().find(|c| c.name == "b").unwrap().clone(),
                new: col("b", ColumnKind::Text, false).default_sql("''"),
            },
        ];
        let (up, down) = sqlite(&changes, &cx).unwrap();
        // Migrations run in a transaction, which `defer_foreign_keys` needs.
        crate::db::script(&db, &format!("BEGIN;\n{up}COMMIT;"))
            .await
            .unwrap();
        let mid = table_columns(&db, "rb_posts").await.unwrap();
        assert!(mid.iter().any(|c| c.name == "b" && c.not_null));
        assert_eq!(
            crate::db::sql("SELECT COUNT(*) FROM rb_posts")
                .scalar::<i64>(&db)
                .await
                .unwrap(),
            2
        );
        assert_eq!(table_indexes(&db, "rb_posts").await.unwrap().len(), 1);
        let violations = crate::db::sql("SELECT COUNT(*) FROM pragma_foreign_key_check")
            .scalar::<i64>(&db)
            .await
            .unwrap();
        assert_eq!(violations, 0);
        crate::db::script(&db, &format!("BEGIN;\n{down}COMMIT;"))
            .await
            .unwrap();
        let after = table_columns(&db, "rb_posts").await.unwrap();
        let key = |v: &[TableColumn]| {
            v.iter()
                .map(|c| (c.name.clone(), c.sql_type.to_lowercase(), c.not_null))
                .collect::<Vec<_>>()
        };
        assert_eq!(key(&before), key(&after));
        assert_eq!(table_indexes(&db, "rb_posts").await.unwrap().len(), 1);
    }
